// Report renders design/wounds/timelines.md: what -> when he falls -> when he dies without help / with help, the walk
// to the capsule and the honest risk of the «non-lethal» blows. text(key) gives the Russian text of a key.
func Report(m runtime.Model, text func(key string) string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("<!-- Code generated by ANG from content/world/wounds (world.wounds). DO NOT EDIT. -->\n")
	b.WriteString("# Раны: сроки — что, когда упадёт, когда умрёт без помощи и с помощью\n\n")
	b.WriteString("Генерируется при каждом `generate` теми же прогонами движка `internal/wounds`, что и тесты (док. 97). ")
	fmt.Fprintf(&b, "Кровь %d мл; пороги: слабость %d‰, спутанность %d‰, без сознания %d‰, смерть %d‰ потери. ", m.Blood.VolumeML, m.States.WeakPermille, m.States.ConfusedPermille, m.States.DownPermille, m.States.DeadPermille)
	b.WriteString("Строка — один и тот же заданный канал раны (seed 42); помощь в строке считается удавшейся ")
	b.WriteString("(вероятность успеха — в таблице помощи док. 97); время помощи — момент, когда она начала действовать (начало + время работы). ")
	fmt.Fprintf(&b, "Горизонт — %s. Все числа — предложение (док. 97), сложность одна: `%s`.\n\n", dur(runtime.Horizon), m.Difficulty.ID)
	rows := make([]runtime.Timeline, 0, len(m.Scenarios))
	for _, s := range m.Scenarios {
		tl, err := m.RunScenario(s, runtime.ScenarioSeed)
		if err != nil {
			return nil, err
		}
		rows = append(rows, tl)
	}
	b.WriteString("## 1. Сроки\n\n| Что | Задето | Упадёт | Без сознания | Умрёт без помощи | Помощь | С помощью |\n|---|---|---|---|---|---|---|\n")
	for i, s := range m.Scenarios {
		tl := rows[i]
		var hit []string
		for _, id := range tl.Wound {
			if st, _, ok := m.Structure(id); ok {
				hit = append(hit, text(st.Name))
			}
		}
		if s.Technique != nil && s.Technique.HoldS > 0 {
			hit = append(hit, fmt.Sprintf("захват %d с", s.Technique.HoldS))
		}
		if s.Condition != "" {
			if c, ok := m.Condition(s.Condition); ok {
				hit = append(hit, text(c.Name))
			}
		}
		help := []string{}
		for _, a := range tl.Aid {
			kind, rest, _ := strings.Cut(a, "@")
			at, reason, _ := strings.Cut(rest, ":")
			var sec int64
			fmt.Sscan(at, &sec)
			name := text(m.Aid.Kinds[kind].Name)
			if reason == "wounds.aid.applied" || reason == "wounds.aid.treated" || reason == "wounds.aid.splinted" {
				extra := ""
				if reason != "wounds.aid.applied" {
					extra = " (" + text(reason) + ")"
				}
				help = append(help, fmt.Sprintf("%s с %s%s", name, dur(sec), extra))
			} else {
				help = append(help, fmt.Sprintf("%s — %s", name, text(reason)))
			}
		}
		aided := "—"
		if len(help) > 0 {
			aided = outcome(tl.AidedFallS, tl.AidedDownS, tl.AidedDeadS)
		} else {
			help = []string{"нет"}
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s |\n", md(text(s.Name)), md(strings.Join(hit, ", ")), when(tl.FallS, "не падает"), when(tl.DownS, "нет"),
			when(tl.DeadS, "выживет"), md(strings.Join(help, "; ")), md(aided))
	}
	b.WriteString("\n## 2. Успеет ли доковылять до медкапсулы\n\n")
	b.WriteString("Пешком раненым шагом от ворот хаба до ниши 16 (план хаба v18, по проходам; капсула в хаб ещё не поставлена — данные). ")
	fmt.Fprintf(&b, "Шаг %d мм/с, снижается эффектами раны и потерей крови. После помощи идёт, когда помощь закончена. ", m.Walk.NormalMMS)
	b.WriteString("Капсула — цена для героя с 10 CRD на счёте по прибытии после помощи; не хватает — бесплатная стабилизация.\n\n")
	head := "| Что |"
	sep := "|---|"
	for _, r := range m.Routes {
		head += fmt.Sprintf(" %s (%s) без помощи | после помощи |", text(r.Name), metres(r.MM))
		sep += "---|---|"
	}
	b.WriteString(head + " Капсула |\n" + sep + "---|\n")
	for i, s := range m.Scenarios {
		tl := rows[i]
		fmt.Fprintf(&b, "| %s |", md(text(s.Name)))
		for j := range m.Routes {
			aided := "—"
			if len(tl.Aid) > 0 {
				aided = walk(tl.AidedWalk[j])
			}
			fmt.Fprintf(&b, " %s | %s |", walk(tl.Walk[j]), aided)
		}
		fmt.Fprintf(&b, " %s |\n", md(capsule(tl.Capsule, text)))
	}
	b.WriteString("\n## 3. Честный риск «нелетальных» приёмов и ударов\n\n")
	b.WriteString("Тот же удар с катящимися глубиной и задетым (Монте-Карло по seed), без помощи. «Насмерть быстро» — смерть за 10 минут, ")
	b.WriteString("когда помощь почти никогда не успевает; «смерть без капсулы» — за неделю, если раненого никто не доведёт до капсулы. ")
	b.WriteString("Безопасного оглушения нет.\n\n| Удар | Прогонов | Упал за минуту | Без сознания за минуту | Серьёзная рана | Насмерть быстро | Смерть без капсулы |\n|---|---|---|---|---|---|---|\n")
	for i, s := range m.Scenarios {
		r := rows[i].Risk
		if r == nil {
			continue
		}
		fmt.Fprintf(&b, "| %s | %d | %s | %s | %s | %s | %s |\n", md(text(s.Name)), r.Runs, pct(r.FallPPM), pct(r.DownPPM), pct(r.SeriousPPM), pct(r.DeadSoonPPM), pct(r.DeadPPM))
	}
	return b.Bytes(), nil
}

func outcome(fall, down, dead int64) string {
	switch {
	case dead >= 0:
		return "умрёт через " + dur(dead)
	case down >= 0:
		return "без сознания с " + dur(down) + ", выживет"
	case fall >= 0:
		return "выживет; упадёт на " + dur(fall)
	}
	return "выживет"
}

func when(s int64, never string) string {
	if s < 0 {
		return never
	}
	return dur(s)
}

func walk(w runtime.WalkRow) string {
	if w.Reached {
		return "да, " + dur(w.AtS)
	}
	if w.AtS <= 0 {
		return "нет: не встаёт, нести"
	}
	return "нет: упадёт на " + dur(w.AtS)
}

func capsule(q runtime.Quote, text func(string) string) string {
	switch q.Mode {
	case "full":
		return fmt.Sprintf("%s CRD, %s", crd(q.PriceMinor), dur(q.Seconds))
	case "stabilize":
		return fmt.Sprintf("полное %s CRD — не хватает: стабилизация %s", crd(q.FullPriceMinor), crdOrFree(q.PriceMinor))
	}
	return text(q.Reason)
}

func crdOrFree(minor int64) string {
	if minor == 0 {
		return "бесплатно"
	}
	return crd(minor) + " CRD"
}

func crd(minor int64) string { return fmt.Sprintf("%d,%02d", minor/100, minor%100) }

func metres(mm int64) string {
	if mm%1000 == 0 {
		return fmt.Sprintf("%d м", mm/1000)
	}
	return fmt.Sprintf("%d,%d м", mm/1000, mm%1000/100)
}

func pct(ppm int64) string {
	if ppm == 0 {
		return "0"
	}
	if ppm < 10000 {
		return fmt.Sprintf("%d,%02d %%", ppm/10000, ppm%10000/100)
	}
	return fmt.Sprintf("%d,%d %%", ppm/10000, ppm%10000/1000)
}

// dur: «14 с», «4 мин 2 с», «1 ч 49 мин», «2 сут 12 ч».
func dur(s int64) string {
	switch {
	case s < 60:
		return fmt.Sprintf("%d с", s)
	case s < 600:
		if s%60 == 0 {
			return fmt.Sprintf("%d мин", s/60)
		}
		return fmt.Sprintf("%d мин %d с", s/60, s%60)
	case s < 3600:
		return fmt.Sprintf("%d мин", (s+30)/60)
	case s < 86400:
		h, mi := s/3600, (s%3600+30)/60
		if mi == 60 {
			h, mi = h+1, 0
		}
		if mi == 0 {
			return fmt.Sprintf("%d ч", h)
		}
		return fmt.Sprintf("%d ч %d мин", h, mi)
	}
	d, h := s/86400, (s%86400+1800)/3600
	if h == 24 {
		d, h = d+1, 0
	}
	if h == 0 {
		return fmt.Sprintf("%d сут", d)
	}
	return fmt.Sprintf("%d сут %d ч", d, h)
}

func md(s string) string { return strings.ReplaceAll(s, "|", "\\|") }
