package gamepoc

import (
	"bytes"
	"encoding/json"
	"fmt"
	"math"
	"sort"
)

// Baseline fixes (21.11.2026, design/world-life/baseline-fixes/BRIEF.md, plan 3; doc 09 «санблок ≤10 мин»): on duty the
// whole absence for the washroom — to the cubicle and back, the doors, the short service (toilet and hands: the basin
// of a cubicle) — fits the brain's hygiene budget, one bound for the brain and the washroom (sanitaryBreak). This list
// shows the duty places from which it cannot fit even with nobody in the queue: a data error to be fixed by data (a
// washroom nearer, a relief worker). Such a person washes at home in the morning and the evening only.

// washroomReach: the report (markdown, generated) or nil when the world has no washroom for the Life's people.
func washroomReach(c Compiled) ([]byte, error) {
	cat := c.SanitaryServices
	if cat == nil || !cat.NPCHygiene || !cat.ServiceAvailable || len(c.Life) == 0 {
		return nil, nil
	}
	var life struct {
		MoveTicks int64 `json:"move_ticks"`
		Brain     struct {
			HygieneSeconds int64 `json:"hygiene_seconds"`
		} `json:"brain"`
		Locations map[string]struct {
			Terrain []string       `json:"terrain"`
			Work    []lifeWorkArea `json:"work"`
			Links   []struct {
				A Point `json:"a"`
				B Point `json:"b"`
			} `json:"links"`
		} `json:"locations"`
		Actors []struct {
			ID    string `json:"id"`
			Name  string `json:"name"`
			Steps []struct {
				Level    string `json:"level"`
				At       Point  `json:"at"`
				Activity string `json:"activity"`
			} `json:"steps"`
		} `json:"actors"`
	}
	if err := json.Unmarshal(c.Life, &life); err != nil {
		return nil, err
	}
	tick := int64(c.Config.TickHz)
	in := int64(math.Ceil((2*cat.DoorSeconds + cat.EntrySeconds) * float64(tick)))
	out := int64(math.Ceil((2*cat.DoorSeconds + cat.ExitSeconds) * float64(tick)))
	units := map[string][]SanitaryUnit{}
	add := func(u SanitaryUnit) {
		if u.Kind == "basin" {
			units[u.LevelID] = append(units[u.LevelID], u)
		}
	}
	for _, u := range cat.Units {
		add(u)
	}
	levels := make([]string, 0, len(cat.Levels))
	for level := range cat.Levels {
		levels = append(levels, level)
	}
	sort.Strings(levels)
	for _, level := range levels {
		for _, u := range cat.Levels[level] {
			add(u)
		}
	}
	type row struct {
		id, name, level string
		at              Point
		cells           int
		total           int64
	}
	var rows []row
	places := 0
	seen := map[string]bool{}
	for _, a := range life.Actors {
		for _, s := range a.Steps {
			if s.Activity != "work" && s.Activity != "service" && s.Activity != "post" || len(units[s.Level]) == 0 {
				continue
			}
			key := fmt.Sprintf("%s|%s|%d|%d", a.ID, s.Level, s.At.X, s.At.Y)
			if seen[key] {
				continue
			}
			seen[key] = true
			places++
			loc := life.Locations[s.Level]
			mine := map[Point]bool{}
			others := map[Point]bool{}
			for _, w := range loc.Work {
				own := false
				for _, id := range w.Workers {
					own = own || id == a.ID
				}
				for _, p := range w.Cells {
					if own {
						mine[p] = true
					} else {
						others[p] = true
					}
				}
			}
			walks := func(p Point) bool {
				return p.Y >= 0 && p.Y < len(loc.Terrain) && p.X >= 0 && p.X < len(loc.Terrain[p.Y]) && c.Walkable[string(loc.Terrain[p.Y][p.X])] && !others[p]
			}
			links := map[Point][]Point{}
			for _, k := range loc.Links {
				links[k.A] = append(links[k.A], k.B)
				links[k.B] = append(links[k.B], k.A)
			}
			dist := map[Point]int{s.At: 0}
			queue := []Point{s.At}
			for head := 0; head < len(queue); head++ {
				at := queue[head]
				near := []Point{{X: at.X + 1, Y: at.Y}, {X: at.X, Y: at.Y + 1}, {X: at.X - 1, Y: at.Y}, {X: at.X, Y: at.Y - 1}}
				for _, n := range append(near, links[at]...) {
					if _, ok := dist[n]; ok || !walks(n) {
						continue
					}
					dist[n] = dist[at] + 1
					queue = append(queue, n)
				}
			}
			best, cells := int64(-1), -1
			for _, u := range units[s.Level] {
				d, ok := dist[u.EntryCell]
				if !ok {
					continue
				}
				total := 2*int64(d)*life.MoveTicks + in + u.ServiceSeconds + out
				if best < 0 || total < best {
					best, cells = total, d
				}
			}
			if best < 0 || best+cat.DutyMarginSeconds > life.Brain.HygieneSeconds {
				rows = append(rows, row{a.ID, a.Name, s.Level, s.At, cells, best})
			}
		}
	}
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].level != rows[j].level {
			return rows[i].level < rows[j].level
		}
		return rows[i].total > rows[j].total || rows[i].total == rows[j].total && rows[i].id < rows[j].id
	})
	var b bytes.Buffer
	fmt.Fprintf(&b, "<!-- Code generated by ANG (compiler/gamepoc/washroom_reach.go). DO NOT EDIT. -->\n")
	fmt.Fprintf(&b, "# Санблок на смене: места, откуда за %d с не обернуться\n\n", life.Brain.HygieneSeconds)
	fmt.Fprintf(&b, "Док. 09 «санблок ≤10 мин» (21.11): на смене всё отсутствие — дорога до кабинки и обратно, двери (%d + %d с), туалет и руки (раковина кабинки) — укладывается в %d игровых секунд с запасом %d с (люди на пути, кадр ×30); граница одна у мозга и санузла. Ниже места смены, откуда это не выходит даже без очереди (шаг %d с на клетку). Это ошибка данных: санузел ближе или сменщик. Отсюда человек моется только дома, утром и вечером.\n\n", in, out, life.Brain.HygieneSeconds, cat.DutyMarginSeconds, life.MoveTicks)
	fmt.Fprintf(&b, "Мест смены у санузлов: %d, из них не укладываются: %d.\n\n", places, len(rows))
	if len(rows) > 0 {
		fmt.Fprintf(&b, "| Человек | Уровень | Место | Клеток до кабинки | Всё отсутствие, с |\n|---|---|---|---|---|\n")
		for _, r := range rows {
			cells, total := fmt.Sprint(r.cells), fmt.Sprint(r.total)
			if r.total < 0 {
				cells, total = "—", "нет пути"
			}
			fmt.Fprintf(&b, "| %s (`%s`) | %s | (%d,%d) | %s | %s |\n", r.name, r.id, r.level, r.at.X, r.at.Y, cells, total)
		}
	}
	return b.Bytes(), nil
}
