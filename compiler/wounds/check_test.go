// testdata/catalog.json is a snapshot of world.wounds (content/world/wounds of the game) for the generator's tests.
func snapshot(t *testing.T) runtime.Model {
	t.Helper()
	raw, err := os.ReadFile("testdata/catalog.json")
	if err != nil {
		t.Fatal(err)
	}
	var m runtime.Model
	d := json.NewDecoder(bytes.NewReader(raw))
	d.DisallowUnknownFields()
	if err := d.Decode(&m); err != nil {
		t.Fatal(err)
	}
	return m
}

func world(m runtime.Model) World {
	w := World{Items: map[string]string{}, Weapons: map[string]bool{}, Armor: map[string]bool{}, Persons: map[string]bool{"char.hero": true},
		Crimes:    map[string]string{"crime.killing": "death", "crime.maiming": "wound", "crime.assault": "hit"},
		Responses: map[string]bool{"fight": true, "flight": true, "freeze": true, "appease": true, "withdraw": true},
		Locales:   []string{"ru", "en"}, Texts: map[string]map[string]string{}}
	for _, it := range m.Aid.Items {
		w.Items[it.Item] = "physical"
	}
	for _, k := range m.Aid.Medkits {
		w.Items[k.Item] = "physical"
	}
	for _, wp := range m.Weapons {
		w.Weapons[wp.Weapon] = true
	}
	for _, a := range m.Armor {
		w.Armor[a.Item] = true
	}
	for _, k := range Keys(m) {
		w.Texts[k] = map[string]string{"ru": "т " + k, "en": "t " + k}
	}
	return w
}

func TestCheckAcceptsTheCatalog(t *testing.T) {
	m := snapshot(t)
	if err := Check(m, world(m)); err != nil {
		t.Fatal(err)
	}
}

func TestCheckRejects(t *testing.T) {
	cases := map[string]func(m *runtime.Model, w *World){
		"missing aid item": func(m *runtime.Model, w *World) { delete(w.Items, "item.med_tourniquet") },
		"medkit not physical": func(m *runtime.Model, w *World) {
			w.Items["item.medkit_guard"] = "digital"
		},
		"no english":     func(m *runtime.Model, w *World) { w.Texts["wounds.zone.thigh"] = map[string]string{"ru": "бедро"} },
		"unknown weapon": func(m *runtime.Model, w *World) { delete(w.Weapons, "item.knife_simple") },
		"wrong crime":    func(m *runtime.Model, w *World) { w.Crimes["crime.killing"] = "wound" },
		"thresholds":     func(m *runtime.Model, w *World) { m.States.ConfusedPermille = m.States.DownPermille + 10 },
		"expectation": func(m *runtime.Model, w *World) {
			for i := range m.Scenarios {
				if m.Scenarios[i].ID == "knife_thigh_artery" {
					m.Scenarios[i].Expect.Dead = runtime.When{Never: true}
				}
			}
		},
		"stress response": func(m *runtime.Model, w *World) { w.Responses["panic"] = true },
	}
	for name, mutate := range cases {
		m := snapshot(t)
		w := world(m)
		mutate(&m, &w)
		if err := Check(m, w); err == nil {
			t.Errorf("%s: accepted", name)
		}
	}
}

func TestRenderAndReport(t *testing.T) {
	m := snapshot(t)
	files, err := Render(m)
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"catalog.json", "catalog_data.gen.go", "catalog_generated_test.go", "engine.gen.go", "model.gen.go", "runtime_generated_test.go"} {
		if len(files[name]) == 0 {
			t.Errorf("missing %s", name)
		}
	}
	for name, data := range files {
		if strings.HasSuffix(name, ".go") && !bytes.HasPrefix(data, []byte("// Code generated by ANG. DO NOT EDIT.")) {
			t.Errorf("%s has no generated header", name)
		}
	}
	for i := range m.Scenarios {
		m.Scenarios[i].RiskRuns = min(m.Scenarios[i].RiskRuns, 200)
	}
	r, err := Report(m, func(k string) string { return "«" + k + "»" })
	if err != nil {
		t.Fatal(err)
	}
	s := string(r)
	for _, want := range []string{"## 1. Сроки", "## 2. Успеет ли доковылять", "## 3. Честный риск", "«wounds.scenario.knife_thigh_artery»", "«wounds.structure.femoral_artery»", "«wounds.aid.tourniquet» с 50 с", "«wounds.scenario.stun_blow»", "| 200 |"} {
		if !strings.Contains(s, want) {
			t.Errorf("report lacks %q", want)
		}
	}
	again, _ := Report(m, func(k string) string { return "«" + k + "»" })
	if !bytes.Equal(r, again) {
		t.Error("the report is not reproducible")
	}
}

func TestDurations(t *testing.T) {
	for s, want := range map[int64]string{14: "14 с", 242: "4 мин 2 с", 300: "5 мин", 1601: "27 мин", 6522: "1 ч 49 мин", 216520: "2 сут 12 ч", 7200: "2 ч"} {
		if got := dur(s); got != want {
			t.Errorf("dur(%d) = %q, want %q", s, got, want)
		}
	}
}
