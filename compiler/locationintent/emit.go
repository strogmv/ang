package locationintent

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/strogmv/ang/compiler/blender"
)

const generatedHeader = "// Generated by `ang location derive` from content/world/location_intent; DO NOT EDIT.\n// Change the intent and derive again.\n"

func packageName(short string) string { return strings.NewReplacer(".", "_", "-", "_").Replace(short) }

func camel(short string) string {
	parts := strings.FieldsFunc(short, func(r rune) bool { return r == '_' || r == '.' || r == '-' })
	for i := 1; i < len(parts); i++ {
		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}
	return strings.Join(parts, "")
}

// Files returns the generated sources of one level, keyed by path relative to
// the game's content/world. They take the places the hand-written packages of
// a location occupy today, so the ordinary pipeline reads them unchanged:
//
//	<short>_sdk/generated.cue              catalog.sdk_layout, exit cells, kit passports of the level
//	godot/<short>/generated.cue            authoring, placement, pipeline, finishing
//	godot/<short>/models.json              model_ref -> res:// scene
//	life/<short>.generated.cue             the Life location and its edges in both directions
//	location_intent_generated/<short>.cue  markers, inspections, region, people, localisation, exit zones
func Files(d *Derived) (map[string][]byte, error) {
	name := packageName(d.Short)
	pipeline := blender.Pipeline{ToleranceM: 0.02, Instances: map[string]blender.ArtSpec{}}
	for _, f := range d.Layout.Floor {
		pipeline.Instances[f.ID] = blender.ArtSpec{Greybox: true, Reason: "Floor slab is drawn by the common floor renderer from the derived zones."}
	}
	for _, m := range d.Intent.Mechanisms {
		for n := range m.Guards {
			pipeline.Instances[fmt.Sprintf("%s.guard.%d", m.ID, n)] = blender.ArtSpec{Greybox: true, Reason: "Unseen blocking cells: the fixed parts standing here are drawn by the model of mechanism " + m.ID + "."}
		}
	}
	for _, f := range d.Fixtures {
		if f.ModelRef == "" {
			pipeline.Instances[f.ID] = blender.ArtSpec{Greybox: true, Reason: "No model with ang_id " + f.Kit + " yet; the greybox placeholder carries the ID."}
		} else {
			pipeline.Instances[f.ID] = blender.ArtSpec{Asset: strings.TrimSuffix(d.Models[f.ModelRef], ".tscn") + ".glb", AssetBasis: "godot"}
		}
	}
	for _, h := range d.World.Hidden {
		pipeline.ReservedHidden = append(pipeline.ReservedHidden, blender.HiddenReserve{ID: h.ID, Min: h.MinM, Max: h.MaxM, Reason: h.Reason})
	}
	exits := map[string]any{}
	for _, e := range d.Exits {
		exits[e.ID] = map[string]any{"exit": e.At, "landing": e.Landing, "status": e.Status}
	}
	sdk, err := json.MarshalIndent(map[string]any{
		"catalog": map[string]any{"id": d.Intent.ID, "area_id": d.Intent.Area, "unit_mm": 500, "elevation_m": d.Intent.ElevationM, "sdk_layout": d.Layout, "exits": exits},
		"kit":     map[string]any{"geometries": d.Extra.Geometries},
	}, "", "\t")
	if err != nil {
		return nil, err
	}
	godotBody, err := json.MarshalIndent(map[string]any{"placement": d.Authoring, "pipeline": pipeline, "finishing": d.Finishing}, "", "\t")
	if err != nil {
		return nil, err
	}
	models, err := json.MarshalIndent(d.Models, "", "  ")
	if err != nil {
		return nil, err
	}
	extra, err := json.MarshalIndent(map[string]any{"levels": map[string]any{d.Intent.ID: map[string]any{
		"tier": d.Intent.Tier, "markers": d.World.Markers, "inspections": d.World.Inspections, "region_node": d.World.RegionNode, "region_links": d.World.RegionLinks,
		"people": d.World.People, "localization": d.World.Localization, "missing_kit": d.Missing, "zone_seeds": d.ZoneSeeds, "capped_pockets": d.Capped,
		// exit_zones: floor cells of every leaving edge, for the hub's exit-zone and nameplate rule.
		"exit_zones": exitZones(d),
	}}}, "", "\t")
	if err != nil {
		return nil, err
	}
	life, err := lifeFile(d)
	if err != nil {
		return nil, err
	}
	worldFile, inspectionFile, err := registryFiles(d)
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		name + "_region.generated.cue":          worldFile,
		"inspection/" + name + ".generated.cue": inspectionFile,
		name + "_sdk/generated.cue":             []byte(generatedHeader + "package " + name + "_sdk\n\n" + string(sdk) + "\n"),
		"godot/" + d.Short + "/generated.cue":   []byte(generatedHeader + "package " + name + "_godot\n\n" + string(godotBody) + "\n"),
		// The pipeline reads the pose authority from this exact file name.
		"godot/" + d.Short + "/authoring.cue":        []byte(generatedHeader + "package " + name + "_godot\n\nauthoring: {pose_source: \"cue\"}\n"),
		"godot/" + d.Short + "/models.json":          append(models, '\n'),
		"life/" + name + ".generated.cue":            life,
		"location_intent_generated/" + name + ".cue": []byte(generatedHeader + "package location_intent_generated\n\n" + string(extra) + "\n"),
	}, nil
}

func exitZones(d *Derived) []map[string]any {
	out := []map[string]any{}
	for _, e := range d.World.LifeEdges {
		if len(e.ExitZone) > 0 {
			out = append(out, map[string]any{"edge": e.ID, "cells": e.ExitZone, "name_key": e.NameKey, "closed_reason_key": e.ClosedReasonKey})
		}
	}
	return out
}

// lifeFile writes the Life location and edges as CUE: the neighbour's cells
// are expressions of package life (the neighbour owns them), ours are literals.
func lifeFile(d *Derived) ([]byte, error) {
	var b strings.Builder
	b.WriteString(generatedHeader + "package life\n\n")
	aliases := make([]string, 0, len(d.Intent.LifeImports))
	for alias := range d.Intent.LifeImports {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)
	if len(aliases) > 0 {
		b.WriteString("import (\n")
		for _, alias := range aliases {
			fmt.Fprintf(&b, "\t%s %q\n", alias, d.Intent.LifeImports[alias])
		}
		b.WriteString(")\n\n")
	}
	fmt.Fprintf(&b, "catalog: locations: %q: {name: %q, modular_layout: %q, initial_layout_known: true, player_range_cells: %d, markers: []}\n", d.Intent.ID, d.World.NameKey, d.Layout.ID, d.World.PlayerRangeCells)
	fmt.Fprintf(&b, "_%sEdges: [\n", camel(d.Short))
	cellCUE := func(c *cell) string { return fmt.Sprintf("{x: %d, y: %d}", c.X, c.Y) }
	for _, e := range d.World.LifeEdges {
		if e.PeerCUE == "" {
			return nil, &Error{Diagnostics: []Diagnostic{{Code: "exit_unbound", ID: e.ID, Message: "the neighbour's cell of this edge is unknown", Hint: "give peer: {exit, entry} as CUE expressions of package life on the exit or mechanism (until the neighbour is built from an intent too)"}}}
		}
		exit, entry := e.PeerCUE, e.PeerCUE
		if e.Exit != nil {
			exit = cellCUE(e.Exit)
		} else {
			entry = cellCUE(e.Entry)
		}
		fmt.Fprintf(&b, "\t{id: %q, ", e.ID)
		if e.ClosedReasonKey != "" {
			fmt.Fprintf(&b, "closed_reason_key: %q, ", e.ClosedReasonKey)
		}
		fmt.Fprintf(&b, "from: %q, to: %q, exit: %s, entry: %s, mode: %q, travel_seconds: %d, period_seconds: %d, seats: %d", e.From, e.To, exit, entry, e.Mode, e.TravelSeconds, e.PeriodSeconds, e.Seats)
		if e.NameKey != "" {
			fmt.Fprintf(&b, ", name_key: %q", e.NameKey)
		}
		if e.Fare != nil {
			fmt.Fprintf(&b, ", fare: {currency: %q, amount_minor: %d, receiver_account: %q}", e.Fare.Currency, e.Fare.AmountMinor, e.Fare.ReceiverAccount)
		}
		b.WriteString("},\n")
	}
	b.WriteString("]\n")
	return []byte(b.String()), nil
}

// Summary is the short human report of one derivation.
func Summary(d *Derived) string {
	codes := []string{}
	for _, m := range d.Missing {
		codes = append(codes, m.ID)
	}
	sort.Strings(codes)
	return fmt.Sprintf("%s: %dx%d cells, %d zones, %d floor areas, %d wall and trim draws, %d capped pockets, %d exits (%d entries), %d fixtures (%d greybox), %d lamps, %d markers, %d inspections, %d Life edges, %d localisation keys; kit without passport: %s",
		d.Intent.ID, d.Layout.Width, d.Layout.Depth, len(d.Zones), len(d.Layout.Floor), len(d.Finishing.Architecture.Draws), len(d.Capped), len(d.Exits), len(d.Layout.Entries), len(d.Fixtures), len(d.Greybox), len(d.Lamps), len(d.World.Markers), len(d.World.Inspections), len(d.World.LifeEdges), len(d.World.Localization), strings.Join(codes, ", "))
}

// registryFiles feed the existing registries of package world and package
// inspection: the region map, wayfinding, localisation and inspection objects.
// Hidden-field names follow the hand-written convention (_copperDockRegionNodes).
func registryFiles(d *Derived) (world, inspection []byte, err error) {
	j := func(v any) string {
		raw, e := json.MarshalIndent(v, "", "\t")
		if e != nil {
			err = e
		}
		return string(raw)
	}
	var b strings.Builder
	b.WriteString(generatedHeader + "package world\n\n")
	n := d.World.RegionNode
	prefix := "_" + camel(d.Short)
	fmt.Fprintf(&b, "%sRegionNodes: %s\n", prefix, j([]map[string]any{{"id": n.ID, "name": n.Name, "deck_id": n.DeckID, "level_id": n.LevelID, "initial_knowledge": n.InitialKnowledge, "description": n.Description}}))
	fmt.Fprintf(&b, "%sRegionLinks: %s\n", prefix, j(d.World.RegionLinks))
	if n.Box != nil {
		fmt.Fprintf(&b, "_regionDiagramBoxes: %q: %s\n", n.ID, j(n.Box))
	}
	if n.Kind != "" {
		fmt.Fprintf(&b, "_regionNodeKinds: %q: %q\n", n.ID, n.Kind)
	}
	fmt.Fprintf(&b, "_regionEnglishNames: %q: %q\n_regionEnglishDescriptions: %q: %q\n", n.ID, n.NameEN, n.ID, n.DescriptionEN)
	markers := []map[string]any{}
	for _, m := range d.World.Markers {
		row := map[string]any{"marker_number": m.Number, "id": m.ID, "name_key": m.Key, "level": d.Intent.ID, "kind": m.Kind, "color": m.Color, "at": m.At}
		if m.GuideFrom != nil {
			row["guide_from"] = m.GuideFrom
		}
		if m.EdgeID != "" {
			row["edge_id"] = m.EdgeID
		}
		markers = append(markers, row)
	}
	fmt.Fprintf(&b, "_wayfindingContributions: %s: %s\n", packageName(d.Short), j(markers))
	texts := []map[string]string{}
	for _, t := range d.World.Localization {
		isInspection := false
		for _, i := range d.World.Inspections {
			isInspection = isInspection || i.TextKey == t.Key
		}
		if !isInspection {
			texts = append(texts, map[string]string{"key": t.Key, "ru": t.RU, "en": t.EN, "context": t.Context})
		}
	}
	objects := []map[string]any{}
	for _, i := range d.World.Inspections {
		nameRU, nameEN := i.Text.NameRU, i.Text.NameEN
		if nameRU == "" || nameEN == "" {
			return nil, nil, &Error{Diagnostics: []Diagnostic{{Code: "inspection_without_name", ID: i.ID, Message: "an inspection needs the object's short name", Hint: "add name_ru and name_en to the inspection text"}}}
		}
		texts = append(texts,
			map[string]string{"key": i.TextKey + ".name", "ru": nameRU, "en": nameEN, "context": "Object name. " + i.Text.Context},
			map[string]string{"key": i.TextKey + ".base", "ru": i.Text.RU, "en": i.Text.EN, "context": i.Text.Context})
		objects = append(objects, map[string]any{"id": i.ID, "level": i.Level, "name": nameRU, "text_key": i.TextKey + ".base", "base_text": i.Text.RU,
			"source": "content/world/location_intent: " + d.Intent.ID, "at": i.At,
			"context": map[string]string{"original_use": i.Purpose, "current_use": i.Purpose, "condition": "—", "author_note": "Выведено из намерения локации; описание не создаёт механику."},
			"facts":   map[string]string{}, "fragments": []any{}})
	}
	fmt.Fprintf(&b, "_intentTranslations: %q: %s\n", d.Intent.ID, j(texts))
	inspection = []byte(generatedHeader + "package inspection\n\n" + fmt.Sprintf("_intentObjects: %q: %s\n", d.Intent.ID, j(objects)))
	return []byte(b.String()), inspection, err
}
