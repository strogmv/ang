package gamepoc

import (
	"encoding/json"
	"fmt"
	"path/filepath"
	"strconv"

	"cuelang.org/go/cue"
	"github.com/strogmv/ang/compiler/questnotation"
)

type dialogueDevAssets struct {
	ToggleAction string
	Paths, Names map[string]string
}

func compileDialogueDev(root string, source, world cue.Value, compiled Compiled) (dialogueDevAssets, error) {
	var input struct {
		ToggleAction string `json:"toggle_action"`
	}
	if err := questRead(source, "developerInput", &input); err != nil {
		return dialogueDevAssets{}, err
	}
	if input.ToggleAction == "" {
		return dialogueDevAssets{}, fmt.Errorf("developerInput.toggle_action is empty")
	}
	m, convs := compiled.Memory, compiled.Conversations
	if m == nil {
		return dialogueDevAssets{ToggleAction: input.ToggleAction}, nil
	}
	scripts, err := readMemoryScripts(root)
	if err != nil {
		return dialogueDevAssets{}, err
	}
	paths, err := questConversationSources(world, root, scripts, convs)
	if err != nil {
		return dialogueDevAssets{}, err
	}
	q := questExport{glossary: map[string]questTerm{}, lex: map[string]questTranslation{}}
	var messages []questTranslation
	if err := questRead(world, "localization.messages", &messages); err != nil {
		return dialogueDevAssets{}, err
	}
	for _, t := range messages {
		q.lex[t.Key] = t
	}
	if err := q.loadTerms(world, m, compiled.Life); err != nil {
		return dialogueDevAssets{}, err
	}
	result := dialogueDevAssets{input.ToggleAction, map[string]string{}, map[string]string{}}
	for id := range convs {
		result.Paths[id] = "quests/" + questActFolder(compiled.StoryActs, id) + paths.path(id)
	}
	for id, term := range q.glossary {
		if term.Name != id {
			result.Names[id] = term.Name
		}
	}
	for id, name := range questAliases {
		result.Names[id] = name
	}
	return result, nil
}

func writeDialogueDev(files map[string][]byte, project string, data dialogueDevAssets) error {
	catalog, err := json.Marshal(data)
	if err != nil {
		return err
	}
	files[filepath.Join(project, "internal/poc/dialogue_dev_catalog.gen.go")] = []byte("// Code generated by ANG. DO NOT EDIT.\npackage poc\n\nconst dialogueDevCatalog = " + strconv.Quote(string(catalog)) + "\n")
	files[filepath.Join(project, "internal/questnotation/notation.gen.go")] = []byte("// Code generated by ANG. DO NOT EDIT.\n" + questnotation.Source)
	input, err := json.Marshal(map[string]string{"toggle_action": data.ToggleAction})
	if err != nil {
		return err
	}
	files[filepath.Join(project, "../client-godot/generated/developer_input.json")] = append(input, '\n')
	return nil
}
