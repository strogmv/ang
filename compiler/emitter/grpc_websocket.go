// RenderGRPCWebSocket adapts protojson to the existing typed bidi handlers.
// It owns only transport I/O; authentication and application sessions stay in Play.
func RenderGRPCWebSocket(def *ir.GRPC, pbImport, pbName string) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by ANG from GRPC.websocket. DO NOT EDIT.
package grpc
import (
 "context"
 "errors"
 "fmt"
 "net"
 "net/http"
 "time"
 "github.com/gorilla/websocket"
 "google.golang.org/grpc"
 "google.golang.org/grpc/codes"
 "google.golang.org/grpc/metadata"
 "google.golang.org/grpc/status"
 "google.golang.org/protobuf/encoding/protojson"
 "google.golang.org/protobuf/proto"
 %s %q
)
// WebSocketOptions deliberately defaults to loopback only. AllowRemote is an
// explicit host opt-in, independent of a supplied bind address.
type WebSocketOptions struct { AllowRemote bool }
func ValidateWebSocketAddress(addr net.Addr, options WebSocketOptions) error {
 host, _, err := net.SplitHostPort(addr.String())
 if err != nil { return err }
 if !options.AllowRemote && !net.ParseIP(host).IsLoopback() { return errors.New("websocket requires loopback; remote access needs explicit opt-in") }
 return nil
}
// ServeWebSocket serves one text protojson envelope per packet. All session,
// authentication, subscription and backpressure logic runs in the same handler
// as gRPC. Cancellation closes upgraded connections, not only HTTP listeners.
func ServeWebSocket(ctx context.Context, listener net.Listener, h Handlers, options WebSocketOptions) error {
 if err := ValidateWebSocketAddress(listener.Addr(), options); err != nil { return err }
 mux := http.NewServeMux()
`, pbName, pbImport)
	for _, s := range def.Services {
		for _, m := range s.Methods {
			if m.Stream != "bidi" {
				continue
			}
			fmt.Fprintf(&b, `
 if h.%s == nil { return errors.New("websocket handler %s is missing") }
 mux.HandleFunc(%q, func(w http.ResponseWriter, r *http.Request) {
  serveProtoSocket(ctx,w,r,options,func(stream grpc.ServerStream) error {
   return h.%s.%s(&grpc.GenericServerStream[%s.%s,%s.%s]{ServerStream:stream})
  })
 })
`, s.Name, s.Name, "/"+def.Package+"."+s.Name+"/"+m.Name, s.Name, m.Name, pbName, m.Request, pbName, m.Response)
		}
	}
	b.WriteString(`
 server := &http.Server{Handler:mux, ReadHeaderTimeout:3*time.Second}
 done := make(chan struct{}); defer close(done)
 go func(){select {case <-ctx.Done():_ = server.Close();case <-done:}}()
 err := server.Serve(listener)
 if errors.Is(err,http.ErrServerClosed) { return nil }; return err
}
func serveProtoSocket(parent context.Context,w http.ResponseWriter,r *http.Request,options WebSocketOptions,play func(grpc.ServerStream)error) {
 if err:=ValidateWebSocketAddress(stringAddr(r.RemoteAddr),options);err!=nil {http.Error(w,err.Error(),http.StatusForbidden);return}
 upgrade:=websocket.Upgrader{CheckOrigin:func(r *http.Request)bool{return r.Header.Get("Origin")==""||r.Header.Get("Origin")=="http://"+r.Host}}
 conn,err:=upgrade.Upgrade(w,r,nil);if err!=nil{return};defer conn.Close()
 conn.SetReadLimit(16<<20)
 _ = conn.SetReadDeadline(time.Now().Add(10*time.Second)) // Includes first Hello/auth.
 ctx,cancel:=context.WithCancel(parent);defer cancel()
 done:=make(chan struct{});defer close(done)
 go func(){select{case <-ctx.Done():_ = conn.WriteControl(websocket.CloseMessage,websocket.FormatCloseMessage(websocket.CloseGoingAway,"shutdown"),time.Now().Add(time.Second));_ = conn.Close();case <-done:}}()
 stream:=&protoSocket{ctx:ctx,conn:conn}
 err=play(stream)
 code:=websocket.CloseNormalClosure
 if err!=nil {code=websocket.CloseInternalServerErr;if status.Code(err)==codes.Unauthenticated {code=websocket.ClosePolicyViolation}}
 _=conn.WriteControl(websocket.CloseMessage,websocket.FormatCloseMessage(code,status.Code(err).String()),time.Now().Add(time.Second))
}
type stringAddr string
func(a stringAddr)Network()string{return "tcp"}
func(a stringAddr)String()string{return string(a)}
type protoSocket struct{ctx context.Context;conn *websocket.Conn}
func(s *protoSocket)Context()context.Context{return s.ctx}
func(s *protoSocket)SetHeader(metadata.MD)error{return nil}
func(s *protoSocket)SendHeader(metadata.MD)error{return nil}
func(s *protoSocket)SetTrailer(metadata.MD){}
func(s *protoSocket)SendMsg(m any)error{
 message,ok:=m.(proto.Message);if !ok{return fmt.Errorf("expected protobuf message, got %T",m)}
 data,err:=(protojson.MarshalOptions{UseProtoNames:true}).Marshal(message);if err!=nil{return err}
 if len(data)>16<<20{return status.Error(codes.ResourceExhausted,"server envelope exceeds transport limit")}
 _=s.conn.SetWriteDeadline(time.Now().Add(5*time.Second));return s.conn.WriteMessage(websocket.TextMessage,data)
}
func(s *protoSocket)RecvMsg(m any)error{
 kind,data,err:=s.conn.ReadMessage();if err!=nil{return err}
 if kind!=websocket.TextMessage{_ = s.conn.WriteControl(websocket.CloseMessage,websocket.FormatCloseMessage(websocket.CloseUnsupportedData,"protojson text required"),time.Now().Add(time.Second));return status.Error(codes.InvalidArgument,"protojson text required")}
 message,ok:=m.(proto.Message);if !ok{return fmt.Errorf("expected protobuf message, got %T",m)}
 if err=protojson.Unmarshal(data,message);err!=nil{_ = s.conn.WriteControl(websocket.CloseMessage,websocket.FormatCloseMessage(websocket.CloseInvalidFramePayloadData,"invalid protojson"),time.Now().Add(time.Second));return status.Error(codes.InvalidArgument,"invalid protojson")}
 _=s.conn.SetReadDeadline(time.Time{})
 return nil
}
`)
	return format.Source([]byte(b.String()))
}
