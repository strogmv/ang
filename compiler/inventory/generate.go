package inventory

import (
	"embed"
	"fmt"
	"go/format"
	"strings"
)

//go:embed runtime/*.go
var sources embed.FS

// Render emits the same standalone engine used by build-time validation.
func Render() (map[string][]byte, error) {
	entries, err := sources.ReadDir("runtime")
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{}
	for _, entry := range entries {
		data, err := sources.ReadFile("runtime/" + entry.Name())
		if err != nil {
			return nil, err
		}
		name := strings.TrimSuffix(entry.Name(), ".go") + ".gen.go"
		if strings.HasSuffix(entry.Name(), "_test.go") {
			name = strings.TrimSuffix(entry.Name(), "_test.go") + "_generated_test.go"
		}
		formatted, err := format.Source(append([]byte("// Code generated by ANG. DO NOT EDIT.\n"), data...))
		if err != nil {
			return nil, fmt.Errorf("inventory %s: %w", entry.Name(), err)
		}
		out[name] = formatted
	}
	return out, nil
}
