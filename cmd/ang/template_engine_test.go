func TestClassifyTemplateFilePythonPreserveMerge(t *testing.T) {
	root := t.TempDir()
	desired := []byte("class S:\n# ANG:BEGIN_CUSTOM services/user.py\npass\n# ANG:END_CUSTOM services/user.py\n")
	current := []byte("class Old:\n# ANG:BEGIN_CUSTOM services/user.py\nprint('keep')\n# ANG:END_CUSTOM services/user.py\n")
	src := filepath.Join(root, "generated.py")
	if err := os.WriteFile(src, desired, 0o644); err != nil {
		t.Fatal(err)
	}
	rel := filepath.ToSlash(filepath.Join("services", "user.py"))
	abs := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(abs, current, 0o644); err != nil {
		t.Fatal(err)
	}
	gf := templateGeneratedFile{Path: rel, SourcePath: src, Action: "update", DesiredHash: sha256Hex(desired)}
	got := classifyTemplateFile(root, gf, "", false)
	if got.Classification != "safe_drift" || got.MergeStrategy != "python_custom_blocks" || !got.AutoApplicable {
		t.Fatalf("unexpected classification: %#v", got)
	}
}

