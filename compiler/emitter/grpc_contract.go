// GRPCProtoPath is the project-relative path of the proto generated for def,
// buf-style: package game.v1 -> game/v1/game.proto.
func GRPCProtoPath(def *ir.GRPC) string {
	parts := strings.Split(def.Package, ".")
	name := parts[0]
	if len(parts) >= 2 {
		name = parts[len(parts)-2]
	}
	return path.Join(append(append([]string{}, parts...), name+".proto")...)
}

// GRPCGoPackage is the import path and package name of the generated pb code.
func GRPCGoPackage(def *ir.GRPC, module string) (importPath, name string) {
	parts := strings.Split(def.Package, ".")
	name = strings.Join(parts[len(parts)-2:], "")
	if len(parts) < 2 {
		name = parts[0]
	}
	if def.GoPackage != "" {
		if i := strings.LastIndex(def.GoPackage, ";"); i >= 0 {
			return def.GoPackage[:i], def.GoPackage[i+1:]
		}
		return def.GoPackage, path.Base(def.GoPackage)
	}
	if strings.TrimSpace(module) == "" {
		module = "example.com/ang"
	}
	return module + "/internal/transport/grpc/pb/" + strings.Join(parts, "/"), name
}

// RenderGRPCProto renders the declared contract as proto3. The output is a pure
// function of def (everything in it is already sorted by the normalizer).
func RenderGRPCProto(def *ir.GRPC, module string) string {
	var b strings.Builder
	imp, name := GRPCGoPackage(def, module)
	b.WriteString("// Code generated by ANG from the GRPC declaration in cue/api. DO NOT EDIT.\n")
	b.WriteString("// Change the CUE, never this file: the field numbers are the wire contract.\n\n")
	b.WriteString("syntax = \"proto3\";\n\n")
	fmt.Fprintf(&b, "package %s;\n\n", def.Package)
	fmt.Fprintf(&b, "option go_package = %q;\n", imp+";"+name)
	if def.CSharpNamespace != "" {
		fmt.Fprintf(&b, "option csharp_namespace = %q;\n", def.CSharpNamespace)
	}
	b.WriteString("\n")

	for _, s := range def.Services {
		fmt.Fprintf(&b, "service %s {\n", s.Name)
		for i, m := range s.Methods {
			if i > 0 {
				b.WriteString("\n")
			}
			protoComment(&b, "  ", m.Description)
			req, resp := m.Request, m.Response
			switch m.Stream {
			case "client":
				req = "stream " + req
			case "server":
				resp = "stream " + resp
			case "bidi":
				req, resp = "stream "+req, "stream "+resp
			}
			fmt.Fprintf(&b, "  rpc %s(%s) returns (%s);\n", m.Name, req, resp)
		}
		b.WriteString("}\n\n")
	}

	for _, e := range def.Enums {
		protoComment(&b, "", e.Description)
		fmt.Fprintf(&b, "enum %s {\n", e.Name)
		prefix := protoUpperSnake(e.Name)
		fmt.Fprintf(&b, "  %s_UNSPECIFIED = 0;\n", prefix)
		for _, v := range e.Values {
			protoComment(&b, "  ", v.Description)
			fmt.Fprintf(&b, "  %s_%s = %d;\n", prefix, v.Name, v.Number)
		}
		protoReserved(&b, e.Reserved, e.ReservedNames)
		b.WriteString("}\n\n")
	}

	for _, m := range def.Messages {
		protoComment(&b, "", m.Description)
		fmt.Fprintf(&b, "message %s {\n", m.Name)
		for _, f := range m.Fields {
			protoComment(&b, "  ", f.Description)
			fmt.Fprintf(&b, "  %s;\n", protoFieldDecl(f))
		}
		for _, o := range m.Oneofs {
			fmt.Fprintf(&b, "  oneof %s {\n", o.Name)
			for _, f := range o.Members {
				protoComment(&b, "    ", f.Description)
				fmt.Fprintf(&b, "    %s;\n", protoFieldDecl(f))
			}
			b.WriteString("  }\n")
		}
		protoReserved(&b, m.Reserved, m.ReservedNames)
		b.WriteString("}\n\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

func protoFieldDecl(f ir.GRPCField) string {
	typ := f.Type
	switch {
	case f.MapKey != "":
		typ = fmt.Sprintf("map<%s, %s>", f.MapKey, f.Type)
	case f.Repeated:
		typ = "repeated " + typ
	case f.Optional:
		typ = "optional " + typ
	}
	decl := fmt.Sprintf("%s %s = %d", typ, f.Name, f.Number)
	if f.Deprecated {
		decl += " [deprecated = true]"
	}
	return decl
}

func protoReserved(b *strings.Builder, nums []int, names []string) {
	if len(nums) > 0 {
		parts := make([]string, len(nums))
		for i, n := range nums {
			parts[i] = fmt.Sprint(n)
		}
		fmt.Fprintf(b, "  reserved %s;\n", strings.Join(parts, ", "))
	}
	if len(names) > 0 {
		parts := make([]string, len(names))
		for i, n := range names {
			parts[i] = fmt.Sprintf("%q", n)
		}
		fmt.Fprintf(b, "  reserved %s;\n", strings.Join(parts, ", "))
	}
}

func protoComment(b *strings.Builder, indent, text string) {
	for _, line := range strings.Split(strings.TrimSpace(text), "\n") {
		if strings.TrimSpace(line) != "" {
			fmt.Fprintf(b, "%s// %s\n", indent, strings.TrimSpace(line))
		}
	}
}

// protoUpperSnake: TileKind -> TILE_KIND, Hello -> HELLO.
func protoUpperSnake(name string) string {
	var out []rune
	for i, r := range name {
		if i > 0 && r >= 'A' && r <= 'Z' {
			out = append(out, '_')
		}
		out = append(out, r)
	}
	return strings.ToUpper(string(out))
}

// emitGRPCContract writes the proto (and its copies); the caller has def != nil.
func (e *Emitter) emitGRPCContract(def *ir.GRPC) error {
	src := []byte(RenderGRPCProto(def, e.GoModule))
	rel := filepath.FromSlash(GRPCProtoPath(def))
	main := e.outDir(append([]string{"api", "grpc"}, strings.Split(filepath.ToSlash(rel), "/")...)...)
	if err := WriteFileIfChanged(main, src, 0o644); err != nil {
		return fmt.Errorf("write grpc proto: %w", err)
	}
	logGenerated("Generated gRPC Proto: %s\n", main)
	return nil
}

// RenderGRPCServer renders internal/transport/grpc/server.gen.go: the listener,
// registration of the hand-written handlers, reflection and the interceptors.
func RenderGRPCServer(def *ir.GRPC, pbImport, pbName string) []byte {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("// Code generated by ANG from the GRPC declaration in cue/api. DO NOT EDIT.\n\n")
	w("package grpc\n\n")
	w("import (\n\t\"context\"\n\t\"errors\"\n\t\"fmt\"\n\t\"log/slog\"\n\t\"net\"\n\t\"runtime/debug\"\n\t\"time\"\n\n")
	w("\t\"google.golang.org/grpc\"\n\t\"google.golang.org/grpc/codes\"\n")
	if def.Reflection {
		w("\t\"google.golang.org/grpc/reflection\"\n")
	}
	w("\t\"google.golang.org/grpc/status\"\n\n\t%s %q\n)\n\n", pbName, pbImport)

	w("// DefaultListen is the address declared by `listen:` in the GRPC declaration.\nconst DefaultListen = %q\n\n", def.Listen)
	w("// Handlers are the hand-written implementations, one per declared service.\n// Embed %s.Unimplemented<Service>Server in each so a new rpc in CUE compiles.\ntype Handlers struct {\n", pbName)
	for _, s := range def.Services {
		w("\t%s %s.%sServer\n", s.Name, pbName, s.Name)
	}
	w("}\n\n")

	w("// NewServer registers the handlers on a grpc.Server with recovery and logging interceptors.\n")
	w("func NewServer(h Handlers, opts ...grpc.ServerOption) (*grpc.Server, error) {\n")
	for _, s := range def.Services {
		w("\tif h.%s == nil {\n\t\treturn nil, errors.New(\"grpc: Handlers.%s is not set\")\n\t}\n", s.Name, s.Name)
	}
	w("\topts = append([]grpc.ServerOption{grpc.ChainUnaryInterceptor(unaryGuard), grpc.ChainStreamInterceptor(streamGuard)}, opts...)\n")
	w("\tsrv := grpc.NewServer(opts...)\n")
	for _, s := range def.Services {
		w("\t%s.Register%sServer(srv, h.%s)\n", pbName, s.Name, s.Name)
	}
	if def.Reflection {
		w("\treflection.Register(srv)\n")
	}
	w("\treturn srv, nil\n}\n\n")

	w(`// ListenAndServe serves on addr (DefaultListen when empty) until ctx is done, then stops gracefully.
func ListenAndServe(ctx context.Context, addr string, h Handlers, opts ...grpc.ServerOption) error {
	if addr == "" {
		addr = DefaultListen
	}
	srv, err := NewServer(h, opts...)
	if err != nil {
		return err
	}
	lis, err := net.Listen("tcp", addr)
	if err != nil {
		return fmt.Errorf("grpc listen %%s: %%w", addr, err)
	}
	done := make(chan struct{})
	go func() {
		select {
		case <-ctx.Done():
			t := time.AfterFunc(10*time.Second, srv.Stop)
			srv.GracefulStop()
			t.Stop()
		case <-done:
		}
	}()
	slog.Info("grpc listening", "addr", addr)
	err = srv.Serve(lis)
	close(done)
	return err
}

func unaryGuard(ctx context.Context, req any, info *grpc.UnaryServerInfo, next grpc.UnaryHandler) (resp any, err error) {
	start := time.Now()
	defer func() {
		if r := recover(); r != nil {
			slog.Error("grpc panic", "method", info.FullMethod, "panic", r, "stack", string(debug.Stack()))
			err = status.Error(codes.Internal, "internal error")
		}
		slog.Debug("grpc unary", "method", info.FullMethod, "code", status.Code(err), "dur", time.Since(start))
	}()
	return next(ctx, req)
}

func streamGuard(srv any, ss grpc.ServerStream, info *grpc.StreamServerInfo, next grpc.StreamHandler) (err error) {
	start := time.Now()
	defer func() {
		if r := recover(); r != nil {
			slog.Error("grpc panic", "method", info.FullMethod, "panic", r, "stack", string(debug.Stack()))
			err = status.Error(codes.Internal, "internal error")
		}
		slog.Debug("grpc stream", "method", info.FullMethod, "code", status.Code(err), "dur", time.Since(start))
	}()
	return next(srv, ss)
}
`)
	return []byte(b.String())
}

// emitGRPCServer writes the pb code, the stubs and the server for def.
func (e *Emitter) emitGRPCServer(def *ir.GRPC) error {
	imp, pbName := GRPCGoPackage(def, e.GoModule)
	module := strings.TrimSpace(e.GoModule)
	if module == "" {
		module = "example.com/ang"
	}
	if !strings.HasPrefix(imp, module+"/") {
		return fmt.Errorf("GRPC.go_package %q must live inside the module %q", imp, module)
	}
	pbDir := strings.Split(strings.TrimPrefix(imp, module+"/"), "/")

	name, src, err := GeneratePBGo(def, module)
	if err != nil {
		return err
	}
	base := strings.TrimSuffix(name, ".pb.go")
	stubs, err := format.Source(RenderGRPCStubs(def, pbName))
	if err != nil {
		return fmt.Errorf("generated grpc stubs are invalid: %w", err)
	}
	files := map[string][]byte{name: src, base + "_grpc.pb.go": stubs}
	for fname, content := range files {
		p := e.outDir(append(append([]string{}, pbDir...), fname)...)
		if err := WriteFileIfChanged(p, content, 0o644); err != nil {
			return fmt.Errorf("write %s: %w", p, err)
		}
	}
	server, err := format.Source(RenderGRPCServer(def, imp, pbName))
	if err != nil {
		return fmt.Errorf("generated grpc server is invalid: %w", err)
	}
	p := e.outDir("internal", "transport", "grpc", "server.gen.go")
	if err := WriteFileIfChanged(p, server, 0o644); err != nil {
		return fmt.Errorf("write grpc server: %w", err)
	}
	logGenerated("Generated gRPC Transport: %s\n", filepath.Dir(p))
	return nil
}
