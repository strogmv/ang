// Package clothing emits the independently testable clothing-surface SDK.
package clothing

import (
	"embed"
	"encoding/json"
	"fmt"
	"go/format"
	"strings"

	runtime "github.com/strogmv/ang/compiler/clothing/runtime"
)

//go:embed runtime/*.go
var sources embed.FS

// Render emits a standalone package and the exact validated CUE-derived catalog.
// It does not register live inventory, perception, NPC or washing adapters.
func Render(catalog []byte) (map[string][]byte, error) {
	var model runtime.Model
	if err := json.Unmarshal(catalog, &model); err != nil {
		return nil, fmt.Errorf("clothing catalog: %w", err)
	}
	if err := model.Validate(); err != nil {
		return nil, err
	}
	entries, err := sources.ReadDir("runtime")
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{"catalog.json": append([]byte(nil), catalog...)}
	loader := []byte(`// Code generated by ANG. DO NOT EDIT.
package clothing
import (_ "embed"; "encoding/json")
//go:embed catalog.json
var catalogJSON []byte
// Catalog returns an independent validated model decoded from the CUE catalog.
func Catalog()(Model,error){var m Model;if err:=json.Unmarshal(catalogJSON,&m);err!=nil{return m,err};return m,m.Validate()}
`)
	out["catalog_data.gen.go"], err = format.Source(loader)
	if err != nil {
		return nil, err
	}
	out["catalog_generated_test.go"], err = format.Source([]byte(`// Code generated by ANG. DO NOT EDIT.
package clothing
import "testing"
func TestGeneratedCatalog(t *testing.T){if _,err:=Catalog();err!=nil{t.Fatal(err)}}
`))
	if err != nil {
		return nil, err
	}
	for _, entry := range entries {
		data, err := sources.ReadFile("runtime/" + entry.Name())
		if err != nil {
			return nil, err
		}
		name := strings.TrimSuffix(entry.Name(), ".go") + ".gen.go"
		if strings.HasSuffix(entry.Name(), "_test.go") {
			name = strings.TrimSuffix(entry.Name(), "_test.go") + "_generated_test.go"
		}
		data, err = format.Source(append([]byte("// Code generated by ANG. DO NOT EDIT.\n"), data...))
		if err != nil {
			return nil, fmt.Errorf("clothing %s: %w", entry.Name(), err)
		}
		out[name] = data
	}
	return out, nil
}
