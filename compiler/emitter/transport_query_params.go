package emitter

import (
	"fmt"
	"strings"

	"github.com/strogmv/ang/angir/normalizer"
)

// queryParamName is the query key of a typed parameter: the field's JSON
// name, the key the TypeScript SDK sends.
func queryParamName(f normalizer.Field, _ *normalizer.QueryParamSpec) string {
	return JSONName(f.Name)
}

// renderQueryParamCode is the handler code that fills req.<Field> from a
// typed query parameter (@query): parse, answer 400 with the one problem
// shape when the value does not parse or a required one is missing.
func renderQueryParamCode(f normalizer.Field) string {
	spec := normalizer.FieldQueryParam(f.Metadata)
	if spec == nil {
		return ""
	}
	name := queryParamName(f, spec)
	var call, want string
	switch spec.Type {
	case normalizer.QueryTypeInt:
		call, want = fmt.Sprintf("queryParamInt(r, %q)", name), "must be an integer"
	case normalizer.QueryTypeInt64:
		call, want = fmt.Sprintf("queryParamInt64(r, %q)", name), "must be an integer"
	case normalizer.QueryTypeFloat:
		call, want = fmt.Sprintf("queryParamFloat(r, %q)", name), "must be a number"
	case normalizer.QueryTypeBool:
		call, want = fmt.Sprintf("queryParamBool(r, %q)", name), "must be true or false"
	case normalizer.QueryTypeDate:
		call, want = fmt.Sprintf("queryParamTime(r, %q, %q)", name, spec.Format), "must be a date like "+spec.Format
	case normalizer.QueryTypeTime:
		call, want = fmt.Sprintf("queryParamTime(r, %q, %q)", name, spec.Format), "must be a time like "+spec.Format
	case normalizer.QueryTypeStrings:
		call, want = fmt.Sprintf("queryParamStrings(r, %q, %q)", name, spec.Format), ""
	default:
		call, want = fmt.Sprintf("queryParamString(r, %q)", name), ""
	}
	field := ExportName(f.Name)
	var b strings.Builder
	b.WriteString("\t\tif v, ok, err := " + call + "; err != nil {\n")
	b.WriteString(fmt.Sprintf("\t\t\twriteQueryParamError(w, r, %q, %q)\n", name, want))
	b.WriteString("\t\t\treturn\n")
	if spec.Required {
		b.WriteString("\t\t} else if !ok {\n")
		b.WriteString(fmt.Sprintf("\t\t\twriteQueryParamError(w, r, %q, \"is required\")\n", name))
		b.WriteString("\t\t\treturn\n")
		b.WriteString("\t\t} else {\n")
	} else {
		b.WriteString("\t\t} else if ok {\n")
	}
	b.WriteString("\t\t\treq." + field + " = v\n")
	b.WriteString("\t\t}")
	return b.String()
}

// queryParamsSource is internal/transport/http/query_params.go, emitted when
// an endpoint has a typed query parameter.
func queryParamsSource(goModule string) string {
	return `// Code generated by ANG. DO NOT EDIT.

package http

import (
	"net/http"
	"strconv"
	"strings"
	"time"

	"` + goModule + `/internal/pkg/errors"
)

// writeQueryParamError is the one 400 answer for a typed query parameter
// (@query) that does not parse or is missing: problem+json with
// errors: {<parameter>: <what is wrong>}, as for the other request fields.
func writeQueryParamError(w http.ResponseWriter, r *http.Request, name, problem string) {
	errors.WriteError(w, r, errors.NewValidationError("Invalid query", map[string]string{name: problem}))
}

// queryParamString is the first value of a query parameter, trimmed; ok is
// false when it is absent or blank.
func queryParamString(r *http.Request, name string) (string, bool, error) {
	values := r.URL.Query()[name]
	if len(values) == 0 || strings.TrimSpace(values[0]) == "" {
		return "", false, nil
	}
	return strings.TrimSpace(values[0]), true, nil
}

func queryParamInt(r *http.Request, name string) (int, bool, error) {
	raw, ok, _ := queryParamString(r, name)
	if !ok {
		return 0, false, nil
	}
	v, err := strconv.Atoi(raw)
	return v, err == nil, err
}

func queryParamInt64(r *http.Request, name string) (int64, bool, error) {
	raw, ok, _ := queryParamString(r, name)
	if !ok {
		return 0, false, nil
	}
	v, err := strconv.ParseInt(raw, 10, 64)
	return v, err == nil, err
}

func queryParamFloat(r *http.Request, name string) (float64, bool, error) {
	raw, ok, _ := queryParamString(r, name)
	if !ok {
		return 0, false, nil
	}
	v, err := strconv.ParseFloat(raw, 64)
	return v, err == nil, err
}

func queryParamBool(r *http.Request, name string) (bool, bool, error) {
	raw, ok, _ := queryParamString(r, name)
	if !ok {
		return false, false, nil
	}
	v, err := strconv.ParseBool(raw)
	return v, err == nil, err
}

// queryParamTime parses a date or time with layout; a layout without a zone
// reads the value as UTC.
func queryParamTime(r *http.Request, name, layout string) (time.Time, bool, error) {
	raw, ok, _ := queryParamString(r, name)
	if !ok {
		return time.Time{}, false, nil
	}
	v, err := time.Parse(layout, raw)
	return v, err == nil, err
}

// queryParamStrings reads a list: repeated (?id=a&id=b, mode "multi"),
// comma-separated (?id=a,b, mode "csv") or both (mode ""). Blank items are
// dropped.
func queryParamStrings(r *http.Request, name, mode string) ([]string, bool, error) {
	var out []string
	for _, raw := range r.URL.Query()[name] {
		parts := []string{raw}
		if mode != "multi" {
			parts = strings.Split(raw, ",")
		}
		for _, part := range parts {
			if part = strings.TrimSpace(part); part != "" {
				out = append(out, part)
			}
		}
		if mode == "csv" {
			break
		}
	}
	return out, len(out) > 0, nil
}
`
}
