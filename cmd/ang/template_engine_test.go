func TestClassifyTemplateFileSafeDriftFromManifest(t *testing.T) {
	root := t.TempDir()
	src := filepath.Join(root, "generated.go")
	desired := []byte("// Code generated by ANG. DO NOT EDIT.\npackage x\n")
	if err := os.WriteFile(src, desired, 0o644); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(root, "file.go")
	current := []byte("// Code generated by ANG. DO NOT EDIT.\npackage old\n")
	if err := os.WriteFile(path, current, 0o644); err != nil {
		t.Fatal(err)
	}
	gf := templateGeneratedFile{Path: "file.go", SourcePath: src, Action: "update", DesiredHash: sha256Hex(desired)}
	got := classifyTemplateFile(root, gf, sha256Hex(current), true)
	if got.Classification != "safe_drift" || !got.AutoApplicable || got.Action != "update" {
		t.Fatalf("unexpected classification: %#v", got)
	}
}

