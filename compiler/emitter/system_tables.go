package emitter

// systemTablesDDL is the one definition of the tables behind the generated
// SystemRepository (systemrepository.go): the transactional outbox, the
// idempotency keys and the key-value state store. EmitSQL writes it at the top
// of db/schema/schema.sql; TestSystemRepositorySQLMatchesSystemTables checks
// that every column the repository reads or writes is declared here.
//
// outbox_events:
//   - topic is the subject the relay publishes to (SaveEvent writes it);
//   - sequence_no gives the delivery order: id is a random UUID, so ListPending
//     orders by sequence_no, an identity assigned at insert time;
//   - event_type is kept nullable for projects whose tables predate topic;
//     the generated code does not use it.
const systemTablesDDL = `-- System Tables for Outbox and Idempotency
CREATE TABLE IF NOT EXISTS outbox_events (
    id UUID PRIMARY KEY,
    event_type TEXT,
    payload JSONB NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ,
    topic TEXT,
    sequence_no BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_outbox_unprocessed ON outbox_events (created_at) WHERE processed_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_outbox_sequence_no ON outbox_events (sequence_no);
CREATE INDEX IF NOT EXISTS idx_outbox_pending_sequence ON outbox_events (sequence_no) WHERE processed_at IS NULL;

CREATE TABLE IF NOT EXISTS idempotency_keys (
    key TEXT PRIMARY KEY,
    response_payload JSONB,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS kv_store (
    key TEXT PRIMARY KEY,
    value BYTEA,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_kv_store_expires ON kv_store (expires_at) WHERE expires_at IS NOT NULL;
`
