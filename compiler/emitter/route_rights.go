package emitter

import (
	"fmt"
	"sort"
	"strings"

	"github.com/strogmv/ang/angir/ir"
)

// routeRightsSource is internal/transport/http/route_rights.go: the right each
// route declares (auth.right), for tests and tools that check a route's gate
// without the router. "" when no route declares one (no file).
func routeRightsSource(endpoints []ir.Endpoint) string {
	var lines []string
	for _, ep := range endpoints {
		if ep.Auth == nil || ep.Auth.Right == "" || strings.EqualFold(ep.Method, "WS") {
			continue
		}
		lines = append(lines, fmt.Sprintf("\t%q: %q,", strings.ToUpper(ep.Method)+" "+ep.Path, ep.Auth.Right))
	}
	if len(lines) == 0 {
		return ""
	}
	sort.Strings(lines)
	return `// Code generated by ANG. DO NOT EDIT.

package http

import "strings"

// routeRights is the right each role-gated route declares (auth.right),
// keyed by "METHOD pattern"; RequireRolesRight hands it to CheckRoleAccess.
var routeRights = map[string]string{
` + strings.Join(lines, "\n") + `
}

// RouteRight is the right the route method+pattern declares (auth.right);
// ok is false for a route that declares none.
func RouteRight(method, pattern string) (right string, ok bool) {
	right, ok = routeRights[strings.ToUpper(method)+" "+pattern]
	return right, ok
}
`
}
