// helperFilePrefix starts the file of every shared helper in internal/service.
const helperFilePrefix = "helper__"

// emitHelpers writes each shared helper (Helpers: in cue/api) once: a func,
// type, var or const to its own file, a method helper to its own file with
// one copy per service whose operations reach it (receiver *<Service>Impl).
// The code keeps its lines, so a //line directive maps it to the CUE literal
// it is written in. Helper files no longer generated are removed.
func (e *Emitter) emitHelpers(targetDir string, helpers []ir.Helper, services []normalizer.Service) error {
	keep := map[string]struct{}{}
	if len(helpers) > 0 {
		for _, svc := range services {
			if strings.ToLower(svc.Name)+"__" == helperFilePrefix {
				return fmt.Errorf("service %s: its operation files (%s<op>.gen.go) would mix with the helper files; rename the service", svc.Name, helperFilePrefix)
			}
		}
	}
	kinds := make(map[string]string, len(helpers))
	for _, h := range helpers {
		kinds[h.Name] = h.Kind
	}
	users := map[string][]string{} // method helper → services, sorted
	for _, svc := range services {
		for _, name := range normalizer.ServiceMethodHelpers(svc, kinds) {
			users[name] = append(users[name], svc.Name)
		}
	}
	sorted := append([]ir.Helper(nil), helpers...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })
	for _, h := range sorted {
		var receivers []string
		if h.Kind == normalizer.HelperMethod {
			for _, svc := range users[h.Name] {
				receivers = append(receivers, svc+"Impl")
			}
			sort.Strings(receivers)
			if len(receivers) == 0 {
				continue // no service calls it (validate warned: HELPER_UNUSED)
			}
		}
		name := normalizer.HelperFileName(h.Name)
		keep[name] = struct{}{}
		src, err := e.renderHelperFile(h, receivers)
		if err != nil {
			return err
		}
		unit := "internal/service/" + name
		formatted, err := formatGoStrict(src, unit)
		if err != nil {
			return fmt.Errorf("helper %s (%s): %w", h.Name, h.Source, err)
		}
		formatted = finalizeLineDirectives(formatted, e.sourceBackendPath("internal", "service", name))
		path := filepath.Join(targetDir, name)
		if err := writeFileAtomic(path, formatted, 0644); err != nil {
			return err
		}
		logGenerated("Generated Helper: %s\n", path)
	}
	return pruneGeneratedFiles(
		targetDir,
		keep,
		func(name string) bool {
			return strings.HasPrefix(name, helperFilePrefix) && strings.HasSuffix(name, ".gen.go")
		},
		func(path string) bool {
			return fileContainsAny(path, "Code generated by ANG", "DO NOT EDIT")
		},
	)
}

// renderHelperFile is the unformatted file of one helper: the service base
// imports plus the helper's own (goimports drops the unused and adds what
// the code uses beyond them), then the code — once, or once per receiver.
func (e *Emitter) renderHelperFile(h ir.Helper, receivers []string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(e.renderGeneratedHeader([]string{h.Source}))
	b.WriteString("package service\n\nimport (\n")
	seen := map[string]bool{}
	writeImport := func(alias, path string) {
		spec := fmt.Sprintf("%q", path)
		if alias != "" {
			spec = alias + " " + spec
		}
		if seen[spec] {
			return
		}
		seen[spec] = true
		b.WriteString("\t" + spec + "\n")
	}
	ownNames := map[string]bool{}
	for _, entry := range h.Imports {
		alias, path := rawgo.NormalizeImport(entry)
		if path == "" {
			continue
		}
		name := alias
		if name == "" {
			name = rawgo.PackageName(path)
		}
		ownNames[name] = true
		writeImport(alias, path)
	}
	for _, path := range rawgo.ServiceBaseImports(e.GoModule) {
		if ownNames[rawgo.PackageName(path)] {
			continue // the helper names its own package for this name
		}
		writeImport("", path)
	}
	b.WriteString(")\n\n")

	code := strings.TrimRight(h.Code, "\n")
	lead := leadingCommentLines(code)
	total := strings.Count(code, "\n") + 1
	marker := ""
	if strings.TrimSpace(h.CodeFile) != "" && h.CodeLine > 0 && total > lead {
		marker = fmt.Sprintf("%s %s:%d %d\n", lineMarkerPrefix, filepath.ToSlash(filepath.Clean(h.CodeFile)), h.CodeLine+lead, total-lead)
	}
	if h.Source != "" {
		fmt.Fprintf(&b, "// Helper %s, declared at %s.\n", h.Name, h.Source)
	}
	if h.Kind != normalizer.HelperMethod {
		b.WriteString(marker)
		b.WriteString(code)
		b.WriteString("\n")
		return b.Bytes(), nil
	}
	for i, recv := range receivers {
		withRecv, err := replaceHelperReceiver(code, recv)
		if err != nil {
			return nil, fmt.Errorf("helper %s (%s): %w", h.Name, h.Source, err)
		}
		if i > 0 {
			b.WriteString("\n")
		}
		b.WriteString(marker)
		b.WriteString(withRecv)
		b.WriteString("\n")
	}
	return b.Bytes(), nil
}

// replaceHelperReceiver turns `func (s *Service) name` into the method of
// the given implementation type, in place: the code keeps its lines.
func replaceHelperReceiver(code, implType string) (string, error) {
	const header = "package helper\n"
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "helper.go", header+code, parser.SkipObjectResolution)
	if err != nil {
		return "", err
	}
	for _, decl := range file.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv == nil || len(fn.Recv.List) != 1 {
			continue
		}
		star, ok := fn.Recv.List[0].Type.(*ast.StarExpr)
		if !ok {
			continue
		}
		id, ok := star.X.(*ast.Ident)
		if !ok || id.Name != normalizer.HelperReceiverType {
			continue
		}
		start := fset.Position(id.Pos()).Offset - len(header)
		end := fset.Position(id.End()).Offset - len(header)
		return code[:start] + implType + code[end:], nil
	}
	return "", fmt.Errorf("no receiver (s *%s) to replace", normalizer.HelperReceiverType)
}

// leadingCommentLines counts the comment and blank lines before the code of
// a helper: they stay unmapped (finalizeLineDirectives skips them).
func leadingCommentLines(code string) int {
	n := 0
	for _, line := range strings.Split(code, "\n") {
		if !isBlankOrComment(line) {
			break
		}
		n++
	}
	return n
}
