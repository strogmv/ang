func TestCUELineLocatorPlacesErrorOnEmbeddedLine(t *testing.T) {
	project := t.TempDir()
	cue := "package api\n\n#Impls: GetThing: flow: [{\n\taction: \"logic.Call\"\n\tfunc: \"\"\"\n\t\t(func(ctx context.Context, id string) error {\n\t\t\titems, err := s.ThingRepo.ListNope(ctx, id)\n\t\t\treturn err\n\t\t})\n\t\t\"\"\"\n}]\n"
	writeTestFile(t, filepath.Join(project, "cue", "api", "impl_thing.cue"), cue)
	generated := "// Code generated by ANG v0 from:\n//   cue/api/impl_thing.cue (sha: 1234)\n// DO NOT EDIT.\n\npackage service\n\nfunc (s *Impl) GetThing(ctx context.Context, id string) error {\n\treturn (func(ctx context.Context, id string) error {\n\t\titems, err := s.ThingRepo.ListNope(ctx, id)\n\t\treturn err\n\t})(ctx, id)\n}\n"
	generatedPath := filepath.Join(t.TempDir(), "thing__get_thing.gen.go")
	writeTestFile(t, generatedPath, generated)

	e := typeCheckError{GeneratedFile: "internal/service/thing__get_thing.gen.go", GeneratedLine: 9, GeneratedColumn: 28, Match: typeCheckMatchNone, contentPath: generatedPath}
	newCUELineLocator(project, filepath.Join(project, "cue")).locate(&e)
	if e.Match != typeCheckMatchExact || e.CUEFile != "cue/api/impl_thing.cue" || e.CUELine != 7 {
		t.Fatalf("located %+v", e)
	}
	// Generated indentation is two tabs, CUE's three: column 28 → 29.
	if e.CUEColumn != 29 {
		t.Fatalf("column = %d, want 29", e.CUEColumn)
	}
	if len(e.From) != 1 || e.From[0] != "cue/api/impl_thing.cue" {
		t.Fatalf("from = %v", e.From)
	}
}

func TestCUELineLocatorPrefersLineWithMatchingNeighbours(t *testing.T) {
	project := t.TempDir()
	cue := "package api\n\nA: \"\"\"\n\tx := load()\n\treturn err\n\t\"\"\"\nB: \"\"\"\n\ty := fetch()\n\treturn err\n\t\"\"\"\n"
	writeTestFile(t, filepath.Join(project, "cue", "api", "two.cue"), cue)
	generatedPath := filepath.Join(t.TempDir(), "x.go")
	writeTestFile(t, generatedPath, "package service\n\nfunc f() error {\n\ty := fetch()\n\treturn err\n}\n")

	e := typeCheckError{GeneratedLine: 5, GeneratedColumn: 9, Match: typeCheckMatchNone, contentPath: generatedPath}
	newCUELineLocator(project, filepath.Join(project, "cue")).locate(&e)
	if e.Match != typeCheckMatchExact || e.CUELine != 9 {
		t.Fatalf("located %+v, want the return under fetch() at line 9", e)
	}
}

func TestCUELineLocatorReportsNoMatch(t *testing.T) {
	project := t.TempDir()
	writeTestFile(t, filepath.Join(project, "cue", "api", "a.cue"), "package api\n")
	generatedPath := filepath.Join(t.TempDir(), "x.go")
	writeTestFile(t, generatedPath, "package service\n\nvar scaffolding = missing\n")
	e := typeCheckError{GeneratedLine: 3, GeneratedColumn: 19, Match: typeCheckMatchNone, contentPath: generatedPath}
	newCUELineLocator(project, filepath.Join(project, "cue")).locate(&e)
	if e.Match != typeCheckMatchNone || e.CUEFile != "" {
		t.Fatalf("located %+v", e)
	}
}

// The compiler sees the dry-run file through -overlay; its error must come
// back under the project path, with the generated text read from the overlay.
func TestGoBuildWithOverlayReportsProjectPaths(t *testing.T) {
	project := t.TempDir()
	writeTestFile(t, filepath.Join(project, "go.mod"), "module example.com/overlaycheck\n\ngo 1.22\n")
	writeTestFile(t, filepath.Join(project, "internal", "service", "thing.gen.go"), "package service\n\nfunc Thing() int { return 1 }\n")

	generatedRoot := t.TempDir()
	writeTestFile(t, filepath.Join(generatedRoot, "internal", "service", "thing.gen.go"), "package service\n\nfunc Thing() int {\n\treturn missingHelper()\n}\n")
	replace, err := generatedGoOverlay(generatedRoot, project)
	if err != nil {
		t.Fatal(err)
	}
	output, buildErr := goBuildWithOverlay(project, replace, []string{"./internal/service/..."}, t.TempDir())
	if buildErr == nil {
		t.Fatalf("the overlay file does not compile; go build succeeded:\n%s", output)
	}
	errs, _ := parseTypeCheckOutput(output, project, replace)
	if len(errs) != 1 {
		t.Fatalf("errors = %+v\noutput:\n%s", errs, output)
	}
	e := errs[0]
	if e.GeneratedFile != "internal/service/thing.gen.go" || e.GeneratedLine != 4 || !strings.Contains(e.Message, "missingHelper") {
		t.Fatalf("error = %+v", e)
	}
	content, err := os.ReadFile(e.contentPath)
	if err != nil || !strings.Contains(string(content), "missingHelper") {
		t.Fatalf("content must be read from the generated file, got %q (%v)", e.contentPath, err)
	}
	if onDisk, _ := os.ReadFile(filepath.Join(project, "internal", "service", "thing.gen.go")); strings.Contains(string(onDisk), "missingHelper") {
		t.Fatal("the project file must not change")
	}
}
