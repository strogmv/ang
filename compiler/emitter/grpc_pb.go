// GeneratePBGo compiles the contract in process (no protoc) and returns the
// protoc-gen-go output for it: the file name relative to the pb directory and
// its source. Same generator, same output as `protoc --go_out`.
func GeneratePBGo(def *ir.GRPC, module string) (name string, src []byte, err error) {
	protoPath := GRPCProtoPath(def)
	text := RenderGRPCProto(def, module)
	c := protocompile.Compiler{
		Resolver: protocompile.WithStandardImports(&protocompile.SourceResolver{
			Accessor: protocompile.SourceAccessorFromMap(map[string]string{protoPath: text}),
		}),
		SourceInfoMode: protocompile.SourceInfoStandard,
	}
	files, err := c.Compile(context.Background(), protoPath)
	if err != nil {
		return "", nil, fmt.Errorf("compile generated proto %s: %w", protoPath, err)
	}
	res, ok := files[0].(linker.Result)
	if !ok {
		return "", nil, fmt.Errorf("compile generated proto %s: unexpected result %T", protoPath, files[0])
	}
	req := &pluginpb.CodeGeneratorRequest{
		FileToGenerate: []string{protoPath},
		Parameter:      strPtr("paths=source_relative"),
		ProtoFile:      []*descriptorpb.FileDescriptorProto{res.FileDescriptorProto()},
	}
	gen, err := protogen.Options{}.New(req)
	if err != nil {
		return "", nil, err
	}
	for _, f := range gen.Files {
		if f.Generate {
			internal_gengo.GenerateFile(gen, f)
		}
	}
	resp := gen.Response()
	if resp.Error != nil {
		return "", nil, fmt.Errorf("protoc-gen-go: %s", resp.GetError())
	}
	if len(resp.File) != 1 {
		return "", nil, fmt.Errorf("protoc-gen-go produced %d files, want 1", len(resp.File))
	}
	return path.Base(resp.File[0].GetName()), []byte(resp.File[0].GetContent()), nil
}

func strPtr(s string) *string { return &s }

// RenderGRPCStubs renders <name>_grpc.pb.go: the service descriptor, the client
// and the server interface, in the shape protoc-gen-go-grpc emits (generic
// stream types), for all four rpc kinds.
func RenderGRPCStubs(def *ir.GRPC, pbName string) []byte {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("// Code generated by ANG from the GRPC declaration in cue/api. DO NOT EDIT.\n\n")
	w("package %s\n\n", pbName)
	w("import (\n\tcontext \"context\"\n\n\tgrpc \"google.golang.org/grpc\"\n\tcodes \"google.golang.org/grpc/codes\"\n\tstatus \"google.golang.org/grpc/status\"\n)\n\n")
	w("const _ = grpc.SupportPackageIsVersion9\n\n")

	for _, s := range def.Services {
		full := def.Package + "." + s.Name
		w("const (\n")
		for _, m := range s.Methods {
			w("\t%s_%s_FullMethodName = \"/%s/%s\"\n", s.Name, m.Name, full, m.Name)
		}
		w(")\n\n")

		// client
		w("// %sClient is the client API for %s.\ntype %sClient interface {\n", s.Name, s.Name, s.Name)
		for _, m := range s.Methods {
			switch m.Stream {
			case "none":
				w("\t%s(ctx context.Context, in *%s, opts ...grpc.CallOption) (*%s, error)\n", m.Name, m.Request, m.Response)
			case "server":
				w("\t%s(ctx context.Context, in *%s, opts ...grpc.CallOption) (grpc.ServerStreamingClient[%s], error)\n", m.Name, m.Request, m.Response)
			case "client":
				w("\t%s(ctx context.Context, opts ...grpc.CallOption) (grpc.ClientStreamingClient[%s, %s], error)\n", m.Name, m.Request, m.Response)
			case "bidi":
				w("\t%s(ctx context.Context, opts ...grpc.CallOption) (grpc.BidiStreamingClient[%s, %s], error)\n", m.Name, m.Request, m.Response)
			}
		}
		w("}\n\n")
		w("type %sClient struct{ cc grpc.ClientConnInterface }\n\n", lowerFirst(s.Name))
		w("func New%sClient(cc grpc.ClientConnInterface) %sClient { return &%sClient{cc} }\n\n", s.Name, s.Name, lowerFirst(s.Name))
		for i, m := range s.Methods {
			recv := lowerFirst(s.Name) + "Client"
			const_ := fmt.Sprintf("%s_%s_FullMethodName", s.Name, m.Name)
			switch m.Stream {
			case "none":
				w("func (c *%s) %s(ctx context.Context, in *%s, opts ...grpc.CallOption) (*%s, error) {\n", recv, m.Name, m.Request, m.Response)
				w("\tcOpts := append([]grpc.CallOption{grpc.StaticMethod()}, opts...)\n\tout := new(%s)\n\tif err := c.cc.Invoke(ctx, %s, in, out, cOpts...); err != nil {\n\t\treturn nil, err\n\t}\n\treturn out, nil\n}\n\n", m.Response, const_)
			case "server":
				w("func (c *%s) %s(ctx context.Context, in *%s, opts ...grpc.CallOption) (grpc.ServerStreamingClient[%s], error) {\n", recv, m.Name, m.Request, m.Response)
				w("\tcOpts := append([]grpc.CallOption{grpc.StaticMethod()}, opts...)\n\tstream, err := c.cc.NewStream(ctx, &%s_ServiceDesc.Streams[%d], %s, cOpts...)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n", s.Name, streamIndex(s, i), const_)
				w("\tx := &grpc.GenericClientStream[%s, %s]{ClientStream: stream}\n\tif err := x.ClientStream.SendMsg(in); err != nil {\n\t\treturn nil, err\n\t}\n\tif err := x.ClientStream.CloseSend(); err != nil {\n\t\treturn nil, err\n\t}\n\treturn x, nil\n}\n\n", m.Request, m.Response)
			case "client", "bidi":
				kind := map[string]string{"client": "ClientStreamingClient", "bidi": "BidiStreamingClient"}[m.Stream]
				w("func (c *%s) %s(ctx context.Context, opts ...grpc.CallOption) (grpc.%s[%s, %s], error) {\n", recv, m.Name, kind, m.Request, m.Response)
				w("\tcOpts := append([]grpc.CallOption{grpc.StaticMethod()}, opts...)\n\tstream, err := c.cc.NewStream(ctx, &%s_ServiceDesc.Streams[%d], %s, cOpts...)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n", s.Name, streamIndex(s, i), const_)
				w("\tx := &grpc.GenericClientStream[%s, %s]{ClientStream: stream}\n\treturn x, nil\n}\n\n", m.Request, m.Response)
			}
		}

		// Named aliases for the stream types, as protoc-gen-go-grpc emits them
		// (this name is also what hand-written handlers write in their signature).
		w("// This type alias is provided for backwards compatibility with existing code that references the prior non-generic stream type by name.\n")
		for _, m := range s.Methods {
			var client, server string
			switch m.Stream {
			case "server":
				client = fmt.Sprintf("grpc.ServerStreamingClient[%s]", m.Response)
				server = fmt.Sprintf("grpc.ServerStreamingServer[%s]", m.Response)
			case "client":
				client = fmt.Sprintf("grpc.ClientStreamingClient[%s, %s]", m.Request, m.Response)
				server = fmt.Sprintf("grpc.ClientStreamingServer[%s, %s]", m.Request, m.Response)
			case "bidi":
				client = fmt.Sprintf("grpc.BidiStreamingClient[%s, %s]", m.Request, m.Response)
				server = fmt.Sprintf("grpc.BidiStreamingServer[%s, %s]", m.Request, m.Response)
			default:
				continue
			}
			w("type %s_%sClient = %s\n", s.Name, m.Name, client)
			w("type %s_%sServer = %s\n\n", s.Name, m.Name, server)
		}

		// server
		w("// %sServer is the server API for %s. Embed Unimplemented%sServer for forward compatibility.\ntype %sServer interface {\n", s.Name, s.Name, s.Name, s.Name)
		for _, m := range s.Methods {
			switch m.Stream {
			case "none":
				w("\t%s(context.Context, *%s) (*%s, error)\n", m.Name, m.Request, m.Response)
			case "server":
				w("\t%s(*%s, grpc.ServerStreamingServer[%s]) error\n", m.Name, m.Request, m.Response)
			case "client":
				w("\t%s(grpc.ClientStreamingServer[%s, %s]) error\n", m.Name, m.Request, m.Response)
			case "bidi":
				w("\t%s(grpc.BidiStreamingServer[%s, %s]) error\n", m.Name, m.Request, m.Response)
			}
		}
		w("\tmustEmbedUnimplemented%sServer()\n}\n\n", s.Name)
		w("// Unimplemented%sServer must be embedded to have forward compatible implementations.\ntype Unimplemented%sServer struct{}\n\n", s.Name, s.Name)
		for _, m := range s.Methods {
			switch m.Stream {
			case "none":
				w("func (Unimplemented%sServer) %s(context.Context, *%s) (*%s, error) {\n\treturn nil, status.Error(codes.Unimplemented, \"method %s not implemented\")\n}\n", s.Name, m.Name, m.Request, m.Response, m.Name)
			case "server":
				w("func (Unimplemented%sServer) %s(*%s, grpc.ServerStreamingServer[%s]) error {\n\treturn status.Error(codes.Unimplemented, \"method %s not implemented\")\n}\n", s.Name, m.Name, m.Request, m.Response, m.Name)
			case "client":
				w("func (Unimplemented%sServer) %s(grpc.ClientStreamingServer[%s, %s]) error {\n\treturn status.Error(codes.Unimplemented, \"method %s not implemented\")\n}\n", s.Name, m.Name, m.Request, m.Response, m.Name)
			case "bidi":
				w("func (Unimplemented%sServer) %s(grpc.BidiStreamingServer[%s, %s]) error {\n\treturn status.Error(codes.Unimplemented, \"method %s not implemented\")\n}\n", s.Name, m.Name, m.Request, m.Response, m.Name)
			}
		}
		w("func (Unimplemented%sServer) mustEmbedUnimplemented%sServer() {}\n\n", s.Name, s.Name)
		w("func Register%sServer(s grpc.ServiceRegistrar, srv %sServer) {\n\ts.RegisterService(&%s_ServiceDesc, srv)\n}\n\n", s.Name, s.Name, s.Name)

		for _, m := range s.Methods {
			h := fmt.Sprintf("_%s_%s_Handler", s.Name, m.Name)
			switch m.Stream {
			case "none":
				w("func %s(srv any, ctx context.Context, dec func(any) error, interceptor grpc.UnaryServerInterceptor) (any, error) {\n", h)
				w("\tin := new(%s)\n\tif err := dec(in); err != nil {\n\t\treturn nil, err\n\t}\n\tif interceptor == nil {\n\t\treturn srv.(%sServer).%s(ctx, in)\n\t}\n", m.Request, s.Name, m.Name)
				w("\tinfo := &grpc.UnaryServerInfo{Server: srv, FullMethod: %s_%s_FullMethodName}\n", s.Name, m.Name)
				w("\thandler := func(ctx context.Context, req any) (any, error) {\n\t\treturn srv.(%sServer).%s(ctx, req.(*%s))\n\t}\n\treturn interceptor(ctx, in, info, handler)\n}\n\n", s.Name, m.Name, m.Request)
			case "server":
				w("func %s(srv any, stream grpc.ServerStream) error {\n\tm := new(%s)\n\tif err := stream.RecvMsg(m); err != nil {\n\t\treturn err\n\t}\n", h, m.Request)
				w("\treturn srv.(%sServer).%s(m, &grpc.GenericServerStream[%s, %s]{ServerStream: stream})\n}\n\n", s.Name, m.Name, m.Request, m.Response)
			case "client", "bidi":
				w("func %s(srv any, stream grpc.ServerStream) error {\n", h)
				w("\treturn srv.(%sServer).%s(&grpc.GenericServerStream[%s, %s]{ServerStream: stream})\n}\n\n", s.Name, m.Name, m.Request, m.Response)
			}
		}

		w("// %s_ServiceDesc is the grpc.ServiceDesc for %s. It is for use with Register%sServer only.\n", s.Name, s.Name, s.Name)
		w("var %s_ServiceDesc = grpc.ServiceDesc{\n\tServiceName: \"%s\",\n\tHandlerType: (*%sServer)(nil),\n\tMethods: []grpc.MethodDesc{\n", s.Name, full, s.Name)
		for _, m := range s.Methods {
			if m.Stream == "none" {
				w("\t\t{MethodName: \"%s\", Handler: _%s_%s_Handler},\n", m.Name, s.Name, m.Name)
			}
		}
		w("\t},\n\tStreams: []grpc.StreamDesc{\n")
		for _, m := range s.Methods {
			if m.Stream == "none" {
				continue
			}
			w("\t\t{StreamName: \"%s\", Handler: _%s_%s_Handler, ServerStreams: %t, ClientStreams: %t},\n", m.Name, s.Name, m.Name, m.Stream == "server" || m.Stream == "bidi", m.Stream == "client" || m.Stream == "bidi")
		}
		w("\t},\n\tMetadata: \"%s\",\n}\n\n", GRPCProtoPath(def))
	}
	return []byte(b.String())
}

// streamIndex is the position of method i among the service's streaming rpcs
// (grpc.ServiceDesc.Streams lists only those).
func streamIndex(s ir.GRPCService, i int) int {
	n := 0
	for j := 0; j < i; j++ {
		if s.Methods[j].Stream != "none" {
			n++
		}
	}
	return n
}
