// CSharpNamespace is the namespace protoc gives the message classes: the
// csharp_namespace of the declaration, or the PascalCased package (game.v1 -> Game.V1).
func CSharpNamespace(def *ir.GRPC) string {
	if def.CSharpNamespace != "" {
		return def.CSharpNamespace
	}
	parts := strings.Split(def.Package, ".")
	for i, p := range parts {
		parts[i] = csharpPascal(p)
	}
	return strings.Join(parts, ".")
}

// csharpPascal: move_to -> MoveTo (protoc's property naming for fields and oneof members).
func csharpPascal(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if r == '_' {
			up = true
			continue
		}
		if up && r >= 'a' && r <= 'z' {
			r -= 'a' - 'A'
		}
		up = false
		b.WriteRune(r)
	}
	return b.String()
}

const csharpHeader = "// <auto-generated>\n// Generated by ANG from the GRPC declaration in cue/api. DO NOT EDIT.\n// Change the CUE and rebuild; regenerate with `ang build`.\n// </auto-generated>\n"

// RenderCSharpStubs renders <Service>Grpc.cs: method descriptors and a client per
// service, written against Grpc.Core.Api (CallInvoker), the shape protoc's grpc_csharp_plugin
// emits. Unity reaches it through Grpc.Net.Client's GrpcChannel (a CallInvoker).
func RenderCSharpStubs(def *ir.GRPC, svc ir.GRPCService) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	ns := CSharpNamespace(def)
	full := def.Package + "." + svc.Name
	w("%s#pragma warning disable 0414, 1591, 8981\n\n", csharpHeader)
	w("using System;\nusing System.Threading;\nusing Google.Protobuf;\nusing Grpc.Core;\n\nnamespace %s\n{\n", ns)

	holder := svc.Name + "Grpc"
	w("    /// <summary>Method descriptors of %s.</summary>\n    public static class %s\n    {\n", full, holder)
	w("        public const string ServiceName = %q;\n\n", full)
	seen := map[string]bool{}
	for _, m := range svc.Methods {
		for _, t := range []string{m.Request, m.Response} {
			if seen[t] {
				continue
			}
			seen[t] = true
			w("        static readonly Marshaller<%s> Marshaller%s = Marshallers.Create(msg => msg.ToByteArray(), data => %s.Parser.ParseFrom(data));\n", t, t, t)
		}
	}
	w("\n")
	for _, m := range svc.Methods {
		mt := map[string]string{"none": "Unary", "server": "ServerStreaming", "client": "ClientStreaming", "bidi": "DuplexStreaming"}[m.Stream]
		w("        public static readonly Method<%s, %s> %sMethod = new Method<%s, %s>(MethodType.%s, ServiceName, %q, Marshaller%s, Marshaller%s);\n",
			m.Request, m.Response, m.Name, m.Request, m.Response, mt, m.Name, m.Request, m.Response)
	}
	w("    }\n\n")

	client := svc.Name + "Client"
	w("    public class %s : ClientBase<%s>\n    {\n", client, client)
	w("        public %s(ChannelBase channel) : base(channel) { }\n", client)
	w("        public %s(CallInvoker callInvoker) : base(callInvoker) { }\n", client)
	w("        protected %s() : base() { }\n", client)
	w("        protected %s(ClientBaseConfiguration configuration) : base(configuration) { }\n\n", client)
	for _, m := range svc.Methods {
		d := fmt.Sprintf("%s.%sMethod", holder, m.Name)
		switch m.Stream {
		case "none":
			w("        public virtual %s %s(%s request, CallOptions options) => CallInvoker.BlockingUnaryCall(%s, null, options, request);\n", m.Response, m.Name, m.Request, d)
			w("        public virtual AsyncUnaryCall<%s> %sAsync(%s request, Metadata headers = null, DateTime? deadline = null, CancellationToken cancellationToken = default) => %sAsync(request, new CallOptions(headers, deadline, cancellationToken));\n", m.Response, m.Name, m.Request, m.Name)
			w("        public virtual AsyncUnaryCall<%s> %sAsync(%s request, CallOptions options) => CallInvoker.AsyncUnaryCall(%s, null, options, request);\n", m.Response, m.Name, m.Request, d)
		case "server":
			w("        public virtual AsyncServerStreamingCall<%s> %s(%s request, Metadata headers = null, DateTime? deadline = null, CancellationToken cancellationToken = default) => %s(request, new CallOptions(headers, deadline, cancellationToken));\n", m.Response, m.Name, m.Request, m.Name)
			w("        public virtual AsyncServerStreamingCall<%s> %s(%s request, CallOptions options) => CallInvoker.AsyncServerStreamingCall(%s, null, options, request);\n", m.Response, m.Name, m.Request, d)
		case "client":
			w("        public virtual AsyncClientStreamingCall<%s, %s> %s(Metadata headers = null, DateTime? deadline = null, CancellationToken cancellationToken = default) => %s(new CallOptions(headers, deadline, cancellationToken));\n", m.Request, m.Response, m.Name, m.Name)
			w("        public virtual AsyncClientStreamingCall<%s, %s> %s(CallOptions options) => CallInvoker.AsyncClientStreamingCall(%s, null, options);\n", m.Request, m.Response, m.Name, d)
		case "bidi":
			w("        public virtual AsyncDuplexStreamingCall<%s, %s> %s(Metadata headers = null, DateTime? deadline = null, CancellationToken cancellationToken = default) => %s(new CallOptions(headers, deadline, cancellationToken));\n", m.Request, m.Response, m.Name, m.Name)
			w("        public virtual AsyncDuplexStreamingCall<%s, %s> %s(CallOptions options) => CallInvoker.AsyncDuplexStreamingCall(%s, null, options);\n", m.Request, m.Response, m.Name, d)
		}
	}
	w("\n        protected override %s NewInstance(ClientBaseConfiguration configuration) => new %s(configuration);\n    }\n}\n", client, client)
	return b.String()
}

// oneofOnly returns the members of a message that is exactly one oneof and nothing else.
func oneofOnly(def *ir.GRPC, name string) ([]ir.GRPCField, string, bool) {
	for _, m := range def.Messages {
		if m.Name == name {
			if len(m.Fields) == 0 && len(m.Oneofs) == 1 {
				return m.Oneofs[0].Members, m.Oneofs[0].Name, true
			}
			return nil, "", false
		}
	}
	return nil, "", false
}

// SessionMethods are the bidi rpcs that get a typed Session: request and response
// are both single-oneof wrappers.
func SessionMethods(def *ir.GRPC) []struct {
	Service ir.GRPCService
	Method  ir.GRPCMethod
} {
	var out []struct {
		Service ir.GRPCService
		Method  ir.GRPCMethod
	}
	for _, s := range def.Services {
		for _, m := range s.Methods {
			if m.Stream != "bidi" {
				continue
			}
			if _, _, ok := oneofOnly(def, m.Request); !ok {
				continue
			}
			if _, _, ok := oneofOnly(def, m.Response); !ok {
				continue
			}
			out = append(out, struct {
				Service ir.GRPCService
				Method  ir.GRPCMethod
			}{s, m})
		}
	}
	return out
}

// RenderCSharpSession renders <Service><Method>Session.cs: a Unity-friendly bidi client.
// It has no UnityEngine dependency. Network work runs on pool threads; every event is
// raised from Pump(), which the game calls once per frame on the main thread.
func RenderCSharpSession(def *ir.GRPC, svc ir.GRPCService, m ir.GRPCMethod) string {
	reqMembers, reqOneof, _ := oneofOnly(def, m.Request)
	respMembers, respOneof, _ := oneofOnly(def, m.Response)
	ns := CSharpNamespace(def)
	class := svc.Name + m.Name + "Session"
	client := svc.Name + "Client"
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("%s#pragma warning disable 1591\n\n", csharpHeader)
	w("using System;\nusing System.Collections.Concurrent;\nusing System.Threading;\nusing System.Threading.Tasks;\nusing Grpc.Core;\n\nnamespace %s\n{\n", ns)
	w(`    public enum %[1]sState { Disconnected, Connecting, Connected, Reconnecting, Closed }

    /// <summary>Exponential backoff between reconnect attempts.</summary>
    public sealed class %[1]sReconnectPolicy
    {
        public bool Enabled = true;
        public TimeSpan InitialDelay = TimeSpan.FromMilliseconds(500);
        public TimeSpan MaxDelay = TimeSpan.FromSeconds(10);
        public double Factor = 2.0;
        /// <summary>0 = unlimited.</summary>
        public int MaxAttempts = 0;

        internal TimeSpan Delay(int attempt)
        {
            double ms = InitialDelay.TotalMilliseconds * Math.Pow(Factor, Math.Max(0, attempt - 1));
            return TimeSpan.FromMilliseconds(Math.Min(ms, MaxDelay.TotalMilliseconds));
        }
    }

`, class)
	w("    /// <summary>\n    /// Typed session over %s.%s. Call Start(), then Pump() every frame; subscribe to the On* events.\n    /// The first message of every (re)connection comes from the factory given to the constructor.\n    /// </summary>\n", svc.Name, m.Name)
	w("    public sealed class %s : IDisposable\n    {\n", class)
	w(`        readonly %[1]s _client;
        readonly Func<%[2]s> _first;
        readonly ConcurrentQueue<%[3]s> _inbox = new ConcurrentQueue<%[3]s>();
        readonly ConcurrentQueue<%[2]s> _outbox = new ConcurrentQueue<%[2]s>();
        readonly SemaphoreSlim _outSignal = new SemaphoreSlim(0);
        readonly ConcurrentQueue<Action> _notices = new ConcurrentQueue<Action>();
        CancellationTokenSource _cts;
        Task _loop;
        int _state = (int)%[4]sState.Disconnected;

        public %[4]sReconnectPolicy Reconnect { get; } = new %[4]sReconnectPolicy();
        public int MaxQueuedResponses { get; set; } = 256;
        public int MaxQueuedCommands { get; set; } = 64;
        public bool ResetQueuesOnReconnect { get; set; } = false;
        public %[4]sState State { get { return (%[4]sState)Volatile.Read(ref _state); } }
        /// <summary>Raised from Pump().</summary>
        public event Action<%[4]sState> StateChanged;
        /// <summary>Raised from Pump(). The session keeps retrying if Reconnect.Enabled.</summary>
        public event Action<Exception> Error;
`, client, m.Request, m.Response, class)
	for _, f := range respMembers {
		w("        public event Action<%s> On%s;\n", f.Type, csharpPascal(f.Name))
	}
	w(`        /// <summary>Raised for a response whose oneof is unset (a newer server); never thrown away silently.</summary>
        public event Action<%[1]s> OnUnknown;

        public %[2]s(Grpc.Core.CallInvoker invoker, Func<%[3]s> first)
        {
            if (invoker == null) throw new ArgumentNullException(nameof(invoker));
            _client = new %[4]s(invoker);
            _first = first ?? throw new ArgumentNullException(nameof(first));
        }

        /// <summary>Opens the stream in the background; returns immediately.</summary>
        public void Start()
        {
            if (_loop != null) return;
            _cts = new CancellationTokenSource();
            _loop = Task.Run(() => RunAsync(_cts.Token));
        }

        /// <summary>Queues a message; it is written when the stream is up (after the first message).</summary>
        public void Send(%[3]s message)
        {
            if (message == null) throw new ArgumentNullException(nameof(message));
            if (_outbox.Count >= MaxQueuedCommands) throw new InvalidOperationException("Session command queue is full.");
            _outbox.Enqueue(message);
            _outSignal.Release();
        }
`, m.Response, class, m.Request, client)
	for _, f := range reqMembers {
		w("\n        public void Send%s(%s value) { Send(new %s { %s = value }); }\n", csharpPascal(f.Name), f.Type, m.Request, csharpPascal(f.Name))
	}
	w(`
        /// <summary>Raises queued events on the calling thread. Call once per frame (e.g. from Update()).</summary>
        public int Pump(int maxMessages = int.MaxValue)
        {
            int n = 0;
            Action notice;
            while (_notices.TryDequeue(out notice)) notice();
            %[1]s msg;
            while (n < maxMessages && _inbox.TryDequeue(out msg))
            {
                n++;
                Dispatch(msg);
            }
            return n;
        }

        void Dispatch(%[1]s msg)
        {
            switch (msg.%[2]sCase)
            {
`, m.Response, csharpPascal(respOneof))
	for _, f := range respMembers {
		w("                case %s.%sOneofCase.%s: { var h = On%s; if (h != null) h(msg.%s); break; }\n",
			m.Response, csharpPascal(respOneof), csharpPascal(f.Name), csharpPascal(f.Name), csharpPascal(f.Name))
	}
	w(`                default: { var h = OnUnknown; if (h != null) h(msg); break; }
            }
        }

        void SetState(%[1]sState s)
        {
            if (Interlocked.Exchange(ref _state, (int)s) != (int)s)
            {
                var h = StateChanged;
                if (h != null) _notices.Enqueue(() => h(s));
            }
        }

        void Fail(Exception e)
        {
            var h = Error;
            if (h != null) _notices.Enqueue(() => h(e));
        }

        async Task RunAsync(CancellationToken ct)
        {
            int attempt = 0;
            while (!ct.IsCancellationRequested)
            {
                if (attempt > 0 && ResetQueuesOnReconnect)
                {
                    %[3]s oldRequest;
                    %[4]s oldResponse;
                    while (_outbox.TryDequeue(out oldRequest)) { }
                    while (_inbox.TryDequeue(out oldResponse)) { }
                }
                SetState(attempt == 0 ? %[1]sState.Connecting : %[1]sState.Reconnecting);
                try
                {
                    Task done;
                    // One token per connection: when either side ends, the other is cancelled and
                    // awaited, so a dead call never keeps reading the outbox.
                    using (var link = CancellationTokenSource.CreateLinkedTokenSource(ct))
                    using (var call = _client.%[2]s(cancellationToken: link.Token))
                    {
                        await call.RequestStream.WriteAsync(_first()).ConfigureAwait(false);
                        SetState(%[1]sState.Connected);
                        attempt = 0;
                        var reader = ReadAsync(call, link.Token);
                        var writer = WriteAsync(call, link.Token);
                        done = await Task.WhenAny(reader, writer).ConfigureAwait(false);
                        link.Cancel();
                        try { await Task.WhenAll(reader, writer).ConfigureAwait(false); } catch { }
                    }
                    await done.ConfigureAwait(false); // surfaces the error that ended the connection
                }
                catch (OperationCanceledException) when (ct.IsCancellationRequested) { break; }
                catch (RpcException e) when (e.StatusCode == StatusCode.Cancelled && ct.IsCancellationRequested) { break; }
                catch (Exception e) { Fail(e); }

                if (ct.IsCancellationRequested || !Reconnect.Enabled) break;
                attempt++;
                if (Reconnect.MaxAttempts > 0 && attempt > Reconnect.MaxAttempts) break;
                SetState(%[1]sState.Reconnecting);
                try { await Task.Delay(Reconnect.Delay(attempt), ct).ConfigureAwait(false); }
                catch (OperationCanceledException) { break; }
            }
            SetState(ct.IsCancellationRequested ? %[1]sState.Closed : %[1]sState.Disconnected);
        }

        async Task ReadAsync(AsyncDuplexStreamingCall<%[3]s, %[4]s> call, CancellationToken ct)
        {
            while (await call.ResponseStream.MoveNext(ct).ConfigureAwait(false))
            {
                if (_inbox.Count >= MaxQueuedResponses) throw new InvalidOperationException("Session response queue is full; reconnect and restore state.");
                _inbox.Enqueue(call.ResponseStream.Current);
            }
        }

        async Task WriteAsync(AsyncDuplexStreamingCall<%[3]s, %[4]s> call, CancellationToken ct)
        {
            while (true)
            {
                await _outSignal.WaitAsync(ct).ConfigureAwait(false);
                %[3]s msg;
                if (_outbox.TryDequeue(out msg))
                    await call.RequestStream.WriteAsync(msg).ConfigureAwait(false);
            }
        }

        public void Dispose()
        {
            if (_cts != null) _cts.Cancel();
        }
    }
}
`, class, m.Name, m.Request, m.Response)
	_ = reqOneof
	return b.String()
}
