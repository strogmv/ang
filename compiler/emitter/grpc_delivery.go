package emitter

import (
	"fmt"
	"go/format"
	"strings"

	"github.com/strogmv/ang/angir/ir"
)

// RenderGRPCDelivery generates a per-connection projection in the protobuf package.
// The caller serializes Project, SetSubscription and ResetSnapshots with sends.
func RenderGRPCDelivery(def *ir.GRPC, pbName string) ([]byte, error) {
	if def.ViewSubscription == "" {
		return nil, nil
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by ANG from CUE delivery annotations. DO NOT EDIT.\npackage %s\n\n", pbName)
	b.WriteString(`import (
 "crypto/sha256"
 "fmt"
 "strconv"

 "google.golang.org/protobuf/proto"
 "google.golang.org/protobuf/reflect/protoreflect"
)

type deliveryRule struct { diagnostic bool; revision protoreflect.Name }
var deliveryRules = map[protoreflect.FullName]deliveryRule{
`)
	for _, m := range def.Messages {
		for _, f := range m.Fields {
			switch f.Delivery {
			case "diagnostic":
				fmt.Fprintf(&b, "%q: {diagnostic:true},\n", def.Package+"."+m.Name+"."+f.Name)
			case "static_on_change":
				fmt.Fprintf(&b, "%q: {revision:%q},\n", def.Package+"."+m.Name+"."+f.Name, f.Revision)
			}
		}
	}
	b.WriteString("}\nvar deliveryRevisionFields = map[protoreflect.FullName]bool{\n")
	for _, m := range def.Messages {
		for _, f := range m.Fields {
			if f.Delivery == "static_on_change" {
				fmt.Fprintf(&b, "%q:true,\n", def.Package+"."+m.Name+"."+f.Revision)
			}
		}
	}
	b.WriteString("}\n")
	fmt.Fprintf(&b, `
// ViewProjector is connection-local. Revisions are monotonic per field occurrence
// for its lifetime; reconnect creates a new revision domain and a full snapshot.
// Inputs are immutable after publication, as for ordinary protobuf sends.
type ViewProjector struct {
 subscription *%s
 snapshots map[string]deliverySnapshot
}
type deliverySnapshot struct { hash [32]byte; revision uint64; sent bool }
func NewViewProjector(sub *%s) *ViewProjector {
 p := &ViewProjector{snapshots:map[string]deliverySnapshot{}}
 p.SetSubscription(sub)
 return p
}
// A nil subscription preserves the full legacy profile.
func (p *ViewProjector) SetSubscription(sub *%s) {
 p.subscription = nil
 if sub != nil { p.subscription = proto.Clone(sub).(*%s) }
 p.ResetSnapshots()
}
// ResetSnapshots forces full values after world replacement/save-load without
// moving revisions backwards. Call before publishing the first new-world state.
func (p *ViewProjector) ResetSnapshots() {
 for key, s := range p.snapshots { s.sent = false; p.snapshots[key] = s }
}
func (p *ViewProjector) wantsDiagnostic(name protoreflect.FullName) bool {
 if p.subscription == nil || p.subscription.DiagnosticsAll { return true }
 for _, key := range p.subscription.Diagnostics { if key == string(name) { return true } }
 return false
}
func (p *ViewProjector) Project(input proto.Message) (proto.Message, error) {
 out, err := p.project(input.ProtoReflect(), string(input.ProtoReflect().Descriptor().FullName()))
 if err != nil { return nil, err }
 return out.Interface(), nil
}
`, def.ViewSubscription, def.ViewSubscription, def.ViewSubscription, def.ViewSubscription)
	b.WriteString(`
func (p *ViewProjector) project(m protoreflect.Message, path string) (protoreflect.Message, error) {
 out := m.New()
 fields := m.Descriptor().Fields()
 for i:=0; i<fields.Len(); i++ {
  f := fields.Get(i)
  rule := deliveryRules[f.FullName()]
  if rule.diagnostic && !p.wantsDiagnostic(f.FullName()) { continue }
  key := path+"/"+strconv.Itoa(int(f.Number()))
  v := m.Get(f)
  if rule.revision != "" {
   value := m.New()
   if m.Has(f) { value.Set(f,v) }
   data, err := (proto.MarshalOptions{Deterministic:true}).Marshal(value.Interface())
   if err != nil { return nil, err }
   h := sha256.Sum256(data)
   s := p.snapshots[key]
   if s.revision == 0 || s.hash != h { s.revision++; s.hash = h; s.sent = false }
   out.Set(fields.ByName(rule.revision),protoreflect.ValueOfUint64(s.revision))
   send := p.subscription == nil || !p.subscription.StaticOnChange || !s.sent
   s.sent = true
   p.snapshots[key] = s
   if send && m.Has(f) { out.Set(f,v) }
   continue
  }
  // A generated revision is written by its owning static field, never copied
  // from application defaults (which may appear later in descriptor order).
  if deliveryRevisionFields[f.FullName()] || !m.Has(f) { continue }
  switch {
  case f.IsMap() && f.MapValue().Kind() == protoreflect.MessageKind:
   var projectErr error
   target := out.Mutable(f).Map()
   v.Map().Range(func(k protoreflect.MapKey, val protoreflect.Value) bool {
    child, err := p.project(val.Message(), key+"/"+fmt.Sprintf("%q",fmt.Sprint(k.Interface())))
    if err != nil { projectErr = err; return false }
    target.Set(k,protoreflect.ValueOfMessage(child)); return true
   })
   if projectErr != nil { return nil, projectErr }
  case f.IsList() && f.Kind() == protoreflect.MessageKind:
   target := out.Mutable(f).List()
   for j:=0;j<v.List().Len();j++ {
    child, err := p.project(v.List().Get(j).Message(),key+"/"+strconv.Itoa(j))
    if err != nil { return nil,err }; target.Append(protoreflect.ValueOfMessage(child))
   }
  case !f.IsList() && !f.IsMap() && f.Kind() == protoreflect.MessageKind:
   child, err := p.project(v.Message(),key)
   if err != nil { return nil,err }; out.Set(f,protoreflect.ValueOfMessage(child))
  default: out.Set(f,v)
  }
 }
 out.SetUnknown(m.GetUnknown())
 return out,nil
}
`)
	return format.Source([]byte(b.String()))
}
