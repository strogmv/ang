// Command gen writes ../stdlib.go: the standard library's import paths, and
// the exported names of every package whose name another standard package
// shares (crypto/rand and math/rand), which is where goimports has to guess.
//
//	go generate ./compiler/rawgo
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"regexp"
	"runtime"
	"sort"
	"strings"
)

var exported = regexp.MustCompile(`^\s*(?:func|var|const|type)\s+(?:\([^)]*\)\s*)?([A-Z][A-Za-z0-9_]*)`)

func main() {
	out, err := exec.Command("go", "list", "std").Output()
	if err != nil {
		log.Fatal(err)
	}
	var paths []string
	for _, p := range strings.Fields(string(out)) {
		if p == "internal" || strings.HasPrefix(p, "internal/") || strings.Contains(p, "/internal/") ||
			strings.HasSuffix(p, "/internal") || strings.HasPrefix(p, "vendor/") || strings.HasPrefix(p, "cmd/") {
			continue
		}
		paths = append(paths, p)
	}
	sort.Strings(paths)

	byName := map[string][]string{}
	for _, p := range paths {
		byName[name(p)] = append(byName[name(p)], p)
	}
	symbols := map[string][]string{}
	for _, group := range byName {
		if len(group) < 2 {
			continue
		}
		for _, p := range group {
			doc, err := exec.Command("go", "doc", "-short", p).Output()
			if err != nil {
				log.Fatalf("go doc %s: %v", p, err)
			}
			seen := map[string]bool{}
			for _, line := range strings.Split(string(doc), "\n") {
				if m := exported.FindStringSubmatch(line); m != nil && !seen[m[1]] {
					seen[m[1]] = true
					symbols[p] = append(symbols[p], m[1])
				}
			}
			sort.Strings(symbols[p])
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by compiler/rawgo/gen from `go list std` and `go doc` (%s); DO NOT EDIT.\n\n", runtime.Version())
	b.WriteString("package rawgo\n\n")
	b.WriteString("// stdlibPaths lists the import paths of the standard library (no internal, vendor or cmd).\n")
	b.WriteString("var stdlibPaths = []string{\n")
	for _, p := range paths {
		fmt.Fprintf(&b, "\t%q,\n", p)
	}
	b.WriteString("}\n\n")
	b.WriteString("// stdlibExports lists the exported names of the standard packages that share\n// their name with another standard package.\n")
	b.WriteString("var stdlibExports = map[string][]string{\n")
	keys := make([]string, 0, len(symbols))
	for p := range symbols {
		keys = append(keys, p)
	}
	sort.Strings(keys)
	for _, p := range keys {
		fmt.Fprintf(&b, "\t%q: {", p)
		for i, s := range symbols[p] {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", s)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("stdlib.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// name mirrors rawgo.PackageName for standard paths.
func name(path string) string {
	parts := strings.Split(path, "/")
	n := parts[len(parts)-1]
	if len(parts) > 1 && regexp.MustCompile(`^v[0-9]+$`).MatchString(n) {
		n = parts[len(parts)-2]
	}
	return n
}
