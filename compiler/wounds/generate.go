//go:embed runtime/*.go
var sources embed.FS

// Render emits the standalone engine package and the exact validated catalog (internal/wounds). Nothing calls it from
// combat yet: the fighting layer connects ApplyHit / Tick / ApplyAid (design/wounds/codex-handoff.md).
func Render(m runtime.Model) (map[string][]byte, error) {
	if err := m.Validate(); err != nil {
		return nil, err
	}
	catalog, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{"catalog.json": catalog}
	entries, err := sources.ReadDir("runtime")
	if err != nil {
		return nil, err
	}
	for _, entry := range entries {
		data, err := sources.ReadFile("runtime/" + entry.Name())
		if err != nil {
			return nil, err
		}
		name := strings.TrimSuffix(entry.Name(), ".go") + ".gen.go"
		if strings.HasSuffix(entry.Name(), "_test.go") {
			name = strings.TrimSuffix(entry.Name(), "_test.go") + "_generated_test.go"
		}
		if data, err = format.Source(append([]byte("// Code generated by ANG. DO NOT EDIT.\n"), data...)); err != nil {
			return nil, fmt.Errorf("wounds %s: %w", entry.Name(), err)
		}
		out[name] = data
	}
	loader := []byte(`// Code generated by ANG. DO NOT EDIT.
package wounds
import (_ "embed"; "bytes"; "encoding/json")
//go:embed catalog.json
var catalogJSON []byte
// Catalog returns the validated wound catalog decoded from the CUE catalog (world.wounds).
func Catalog()(Model,error){var m Model;d:=json.NewDecoder(bytes.NewReader(catalogJSON));d.DisallowUnknownFields();if err:=d.Decode(&m);err!=nil{return m,err};return m,m.Validate()}
`)
	if out["catalog_data.gen.go"], err = format.Source(loader); err != nil {
		return nil, err
	}
	if out["catalog_generated_test.go"], err = format.Source([]byte(catalogTest)); err != nil {
		return nil, err
	}
	return out, nil
}

