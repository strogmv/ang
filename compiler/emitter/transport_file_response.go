package emitter

// fileResponseSource is internal/transport/http/file_response.go, emitted when
// an endpoint's operation has a file output (output: {kind: "file"}).
const fileResponseSource = `// Code generated by ANG. DO NOT EDIT.

package http

import (
	"io"
	"net/http"
	"strconv"
	"strings"
	"unicode/utf8"
)

// fileResponseHeaders are what a file answer says about itself: the
// operation's values, else the ones its CUE output declares.
type fileResponseHeaders struct {
	ContentType, Filename               string
	DefaultContentType, DefaultFilename string
	Disposition                         string // "attachment" or "inline"
}

// writeFileResponse writes a file answer: Content-Type, Content-Disposition
// (RFC 6266, with an RFC 5987 filename* for a name that is not ASCII),
// Content-Length when known, then the bytes. A Body is streamed and closed;
// without one, Content is written.
func writeFileResponse(w http.ResponseWriter, body io.ReadCloser, content []byte, size int64, h fileResponseHeaders) {
	if body != nil {
		defer body.Close()
	}
	contentType := firstNonBlank(h.ContentType, h.DefaultContentType, "application/octet-stream")
	header := w.Header()
	header.Set("Content-Type", oneHeaderLine(contentType))
	header.Set("X-Content-Type-Options", "nosniff")
	header.Set("Content-Disposition", contentDisposition(firstNonBlank(h.Disposition, "attachment"), firstNonBlank(h.Filename, h.DefaultFilename)))
	// The answer depended on who asked: a shared cache must not keep it.
	header.Set("Cache-Control", "private")
	if body == nil {
		header.Set("Content-Length", strconv.Itoa(len(content)))
		w.WriteHeader(http.StatusOK)
		_, _ = w.Write(content)
		return
	}
	if size > 0 {
		header.Set("Content-Length", strconv.FormatInt(size, 10))
	}
	w.WriteHeader(http.StatusOK)
	_, _ = io.Copy(w, body)
}

func firstNonBlank(values ...string) string {
	for _, v := range values {
		if strings.TrimSpace(v) != "" {
			return strings.TrimSpace(v)
		}
	}
	return ""
}

func oneHeaderLine(v string) string {
	return strings.NewReplacer("\r", "", "\n", "").Replace(v)
}

// contentDisposition renders disposition; filename="..." holds an ASCII
// stand-in of the name (quotes, backslashes, separators and control
// characters replaced by "_"), filename* the name itself when it is not.
func contentDisposition(disposition, filename string) string {
	filename = oneHeaderLine(filename)
	if filename == "" {
		return disposition
	}
	var ascii strings.Builder
	plain := true
	for _, r := range filename {
		switch {
		case r == '"' || r == '\\' || r == '/' || r < 0x20 || r == 0x7f:
			ascii.WriteByte('_')
		case r >= utf8.RuneSelf:
			ascii.WriteByte('_')
			plain = false
		default:
			ascii.WriteRune(r)
		}
	}
	out := disposition + "; filename=\"" + ascii.String() + "\""
	if !plain {
		out += "; filename*=UTF-8''" + rfc5987Escape(filename)
	}
	return out
}

// rfc5987Escape percent-encodes every byte that is not an attr-char.
func rfc5987Escape(s string) string {
	const hex = "0123456789ABCDEF"
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		if ('a' <= c && c <= 'z') || ('A' <= c && c <= 'Z') || ('0' <= c && c <= '9') || strings.IndexByte("!#$&+-.^_|~", c) >= 0 || c == 0x60 {
			b.WriteByte(c)
			continue
		}
		b.WriteByte('%')
		b.WriteByte(hex[c>>4])
		b.WriteByte(hex[c&15])
	}
	return b.String()
}
`
