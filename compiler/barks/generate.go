//go:embed runtime/*.go
var sources embed.FS

// Render emits the engine package and the exact validated catalog (internal/barks). The live adapter (Life frame, facts,
// gRPC view, combat entry point) is the gamepoc host template barks.go.tmpl.
func Render(m runtime.Model) (map[string][]byte, error) {
	if err := m.Validate(); err != nil {
		return nil, err
	}
	catalog, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{"catalog.json": catalog}
	entries, err := sources.ReadDir("runtime")
	if err != nil {
		return nil, err
	}
	for _, entry := range entries {
		data, err := sources.ReadFile("runtime/" + entry.Name())
		if err != nil {
			return nil, err
		}
		name := strings.TrimSuffix(entry.Name(), ".go") + ".gen.go"
		if strings.HasSuffix(entry.Name(), "_test.go") {
			name = strings.TrimSuffix(entry.Name(), "_test.go") + "_generated_test.go"
		}
		if data, err = format.Source(append([]byte("// Code generated by ANG. DO NOT EDIT.\n"), data...)); err != nil {
			return nil, fmt.Errorf("barks %s: %w", entry.Name(), err)
		}
		out[name] = data
	}
	loader := []byte(`// Code generated by ANG. DO NOT EDIT.
package barks
import (_ "embed"; "encoding/json")
//go:embed catalog.json
var catalogJSON []byte
// Catalog returns the validated model decoded from the CUE catalog (world.barks).
func Catalog()(Model,error){var m Model;if err:=json.Unmarshal(catalogJSON,&m);err!=nil{return m,err};m=m.Sorted();return m,m.Validate()}
`)
	if out["catalog_data.gen.go"], err = format.Source(loader); err != nil {
		return nil, err
	}
	if out["catalog_generated_test.go"], err = format.Source([]byte(`// Code generated by ANG. DO NOT EDIT.
package barks
import "testing"
func TestGeneratedCatalog(t *testing.T){m,err:=Catalog();if err!=nil{t.Fatal(err)};if err:=m.ValidateState(State{},0,0);err!=nil{t.Fatal(err)}}
`)); err != nil {
		return nil, err
	}
	return out, nil
}

// ReportRow is one spoken text of the review report.
type ReportRow struct {
	Place, Speaker, Caste, Face, Reveal, To, When, Tone, React, RU, EN, Register string
	Read                                                                         float64
}

// Report renders design/barks/barks-report.md from the catalog and its texts: place, speaker, caste, face, tone,
// reading time and both languages — for the owner's review of the writing, regenerated with every build.
func Report(m runtime.Model, texts func(key string) map[string]string, context func(key string) string, names func(actor string) string, warnings []string) []byte {
	return ReportWith(m, texts, context, names, warnings, nil)
}

// ReportWith adds the column «регистр en» (barks v2): the register of the speaker's caste in English and the marker the
// line carries, «нет маркера» when a register with markers finds none (the check warns about the same line).
func ReportWith(m runtime.Model, texts func(key string) map[string]string, context func(key string) string, names func(actor string) string, warnings []string, registers map[string]map[string]Register) []byte {
	var b bytes.Buffer
	register := func(caste, en string) string {
		reg, ok := registers[caste]["en"]
		if !ok {
			return "—"
		}
		if len(reg.Markers) == 0 || en == "" {
			return reg.ID
		}
		if mk := RegisterMarker(en, reg.Markers); mk != "" {
			return reg.ID + ": " + mk
		}
		return reg.ID + ": нет маркера"
	}
	b.WriteString("<!-- Code generated by ANG from content/world/barks (world.barks). DO NOT EDIT. -->\n")
	b.WriteString("# Реплики над головой — отчёт для ревью текста\n\n")
	b.WriteString("Генерируется при каждом `generate` из данных. Начертание и появление выводятся из касты говорящего (док. 94), ")
	b.WriteString("время чтения — по формуле док. 94 §3 (появление + удержание, без затухания).\n\n")
	total, combat := 0, len(m.Combat.Lines)
	for _, p := range m.Packs {
		total += len(p.Lines) + len(p.Replies)
	}
	fmt.Fprintf(&b, "Мест: %d · реплик и ответов: %d · боевых: %d · разговоров: %d\n\n", len(m.Packs), total, combat, len(m.Exchanges))
	if len(registers) > 0 {
		b.WriteString("## Регистры речи по кастам (registers.cue)\n\n| Каста | RU | EN | Маркеры EN |\n|---|---|---|---|\n")
		castes := make([]string, 0, len(registers))
		for c := range registers {
			castes = append(castes, c)
		}
		sort.Strings(castes)
		for _, c := range castes {
			ru, en := registers[c]["ru"], registers[c]["en"]
			fmt.Fprintf(&b, "| %s | %s — %s | %s — %s | %s |\n", c, ru.ID, md(ru.Note), en.ID, md(en.Note), md(strings.Join(en.Markers, ", ")))
		}
		b.WriteString("\n")
	}
	row := func(r ReportRow) {
		fmt.Fprintf(&b, "| %s | %s | %s | %s/%s | %s | %s | %.1f с | %s | %s | %s |\n", r.Speaker, r.Caste, r.To, r.Face, r.Reveal, r.When, r.React, r.Read, md(r.RU), md(r.EN), md(r.Register))
		if r.Tone != "" {
			fmt.Fprintf(&b, "| | | | | | | | *%s* | | |\n", md(r.Tone))
		}
	}
	head := "| Говорит | Каста | Кому | Начертание | Когда | Факт | Чтение | RU | EN | Регистр en |\n|---|---|---|---|---|---|---|---|---|---|\n"
	read := func(caste string, ms map[string]runtime.Measure) float64 {
		face, _ := m.Face(caste)
		longest := 0.0
		for _, loc := range m.Locales {
			v := float64(revealMS(m, face, ms[loc])+holdMS(m, ms[loc])) / 1000
			if v > longest {
				longest = v
			}
		}
		return longest
	}
	for _, p := range m.Packs {
		place, _ := m.Place(p.Place)
		fmt.Fprintf(&b, "## %s (%s)\n\n", p.Place, place.Kind)
		fmt.Fprintf(&b, "Слышно в %d клетках · пауза места %d с · не чаще %d в час.\n\n", p.HeroWithinCells, p.GapSeconds, p.MaxPerHour)
		b.WriteString(head)
		for _, l := range p.Lines {
			face, _ := m.Face(l.Caste)
			t := texts(l.ID)
			reacts := []string{}
			for _, r := range l.React {
				reacts = append(reacts, r.Event)
			}
			speaker := names(l.Speaker)
			if l.Speaker == runtime.Anyone {
				speaker = "любой (" + l.Caste + ")"
			}
			row(ReportRow{Speaker: speaker, Caste: l.Caste, Face: face.Face, Reveal: face.Reveal, To: names(l.To), When: strings.Join(l.When, ", "), React: strings.Join(reacts, ", "), Read: read(l.Caste, l.Measure), RU: t["ru"], EN: t["en"], Tone: context(l.ID), Register: register(l.Caste, t["en"])})
		}
		for _, r := range p.Replies {
			face, _ := m.Face(r.Caste)
			if r.Kind == "gesture" {
				row(ReportRow{Speaker: names(r.Speaker), Caste: r.Caste, Face: "жест", Reveal: r.Gesture, To: "ответ", RU: "(" + r.Gesture + ")", EN: "(" + r.Gesture + ")", Register: "—"})
				continue
			}
			t := texts(r.Key)
			row(ReportRow{Speaker: names(r.Speaker), Caste: r.Caste, Face: face.Face, Reveal: face.Reveal, To: "ответ", Read: read(r.Caste, r.Measure), RU: t["ru"], EN: t["en"], Tone: context(r.Key), Register: register(r.Caste, t["en"])})
		}
		b.WriteString("\n")
	}
	if len(m.Exchanges) > 0 {
		fmt.Fprintf(&b, "## Разговоры между людьми (%d)\n\nСлышно рядом с героем; не чаще %d в час на все, пауза %d с. Следующая реплика идёт, только когда прошлая закончилась и оба на месте.\n\n", len(m.Exchanges), m.Talk.MaxPerHour, m.Talk.GapSeconds)
		for _, e := range m.Exchanges {
			fmt.Fprintf(&b, "### %s\n\n%s ↔ %s, ближе %d клеток, повтор не чаще раза в %d мин.\n\n| Кто | RU | EN | Жест | Регистр en |\n|---|---|---|---|---|\n", e.ID, names(e.A.Who), names(e.B.Who), e.WithinCells, e.CooldownSeconds/60)
			for _, t := range e.Turns {
				who, caste := e.A, e.A.Caste
				if t.By == 1 {
					who, caste = e.B, e.B.Caste
				}
				tx := texts(t.ID)
				fmt.Fprintf(&b, "| %s (%s) | %s | %s | %s | %s |\n", names(who.Who), caste, md(tx["ru"]), md(tx["en"]), t.Gesture, md(register(caste, tx["en"])))
			}
			b.WriteString("\n")
		}
	}
	if combat > 0 {
		b.WriteString("## Бой\n\n")
		voices := map[string]runtime.Voice{}
		for _, v := range m.Combat.Voices {
			voices[v.ID] = v
		}
		b.WriteString("| Голос | Каста | Намерение | Начертание | Чтение | RU | EN | Регистр en |\n|---|---|---|---|---|---|---|---|\n")
		lines := append([]runtime.CombatLine(nil), m.Combat.Lines...)
		sort.SliceStable(lines, func(i, j int) bool { return lines[i].Voice < lines[j].Voice })
		for _, l := range lines {
			v := voices[l.Voice]
			if v.Beast {
				fmt.Fprintf(&b, "| %s | зверь | %s | знак %s, звук %s | — | (без слов) | (no words) | — |\n", l.Voice, l.Intent, l.Sign, l.Sfx)
				continue
			}
			face, _ := m.Face(v.Caste)
			t := texts(l.ID)
			fmt.Fprintf(&b, "| %s | %s | %s | %s/%s | %.1f с | %s | %s | %s |\n", l.Voice, v.Caste, l.Intent, face.Face, face.Reveal, read(v.Caste, l.Measure), md(t["ru"]), md(t["en"]), md(register(v.Caste, t["en"])))
		}
		b.WriteString("\n### Ложные намерения (видны только при успешной проверке героя)\n\n")
		for _, d := range m.Combat.Deceptions {
			fmt.Fprintf(&b, "- заявляет `%s`, на деле `%s`:\n", d.Declared, d.Truth)
			for _, t := range d.Tells {
				tx := texts(t.Key)
				fmt.Fprintf(&b, "  - %s ≥ %d: «%s» / “%s”\n", t.Skill, t.Threshold, tx["ru"], tx["en"])
			}
		}
		b.WriteString("\n")
	}
	if len(warnings) > 0 {
		b.WriteString("## Предупреждения проверки\n\n")
		for _, w := range warnings {
			fmt.Fprintf(&b, "- %s\n", w)
		}
	}
	return b.Bytes()
}

func md(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

// the same arithmetic as the engine (runtime.Model.reveal / hold), for the report
func revealMS(m runtime.Model, face runtime.Face, ms runtime.Measure) int64 {
	t := m.Timing
	cps := int64(face.CPS)
	if cps < 1 {
		cps = 1
	}
	switch face.Reveal {
	case "set":
		return t.SetMS
	case "stamped":
		words := int64(max(ms.Words, 1))
		per := max(int64(ms.Runes)*1000/cps/words, t.StampMinMS)
		return per*words + int64(ms.Stops)*t.StopMS/2
	default:
		return int64(ms.Runes)*1000/cps + int64(ms.Commas)*t.CommaMS + int64(ms.Stops)*t.StopMS
	}
}
func holdMS(m runtime.Model, ms runtime.Measure) int64 {
	if m.Timing.WordsPerMinute < 1 {
		return m.Timing.HoldMinMS
	}
	return max(m.Timing.HoldBaseMS+int64(ms.Words)*60000/m.Timing.WordsPerMinute, m.Timing.HoldMinMS)
}
