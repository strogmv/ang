package gamepoc

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// godotPO exports only the public interface vocabulary. Authoring context for
// public keys is an extracted comment; private keys and their contexts never enter.
func godotPO(c LocalizationCatalog) (map[string][]byte, error) {
	if err := c.Validate(); err != nil {
		return nil, err
	}
	if c.DefaultLocale == "" {
		return nil, fmt.Errorf("Godot translations require a localization catalog")
	}
	messages := append([]LocalizationMessage(nil), c.Messages...)
	sort.Slice(messages, func(i, j int) bool { return messages[i].Key < messages[j].Key })
	out := map[string][]byte{}
	for _, locale := range c.Locales {
		var b strings.Builder
		b.WriteString("# Generated by ANG. Public ui.* only. DO NOT EDIT.\nmsgid \"\"\nmsgstr \"\"\n")
		for _, h := range []string{"Content-Type: text/plain; charset=UTF-8\n", "Language: " + strings.ReplaceAll(locale, "-", "_") + "\n", "X-ANG-Default-Locale: " + c.DefaultLocale + "\n", "X-ANG-Fallback-Locale: " + c.FallbackLocale + "\n"} {
			b.WriteString(strconv.Quote(h) + "\n")
		}
		for _, m := range messages {
			if !strings.HasPrefix(m.Key, "ui.") {
				continue
			}
			value := m.Texts[locale]
			if value == "" {
				value = m.Texts[c.FallbackLocale]
			}
			if value == "" {
				value = m.Texts[c.DefaultLocale]
			}
			if value == "" {
				return nil, fmt.Errorf("Godot public key %s has no %s/default/fallback translation", m.Key, locale)
			}
			b.WriteString("\n")
			for _, line := range strings.Split(strings.ReplaceAll(m.Context, "\r", ""), "\n") {
				b.WriteString("#. " + line + "\n")
			}
			b.WriteString("msgid " + strconv.Quote(m.Key) + "\nmsgstr " + strconv.Quote(value) + "\n")
		}
		out[locale] = []byte(b.String())
	}
	return out, nil
}

// godotProjectLocales owns only these settings, preserving the other sections.
func godotProjectLocales(raw string, c LocalizationCatalog) string {
	locales := append([]string(nil), c.Locales...)
	sort.Strings(locales)
	paths := make([]string, 0, len(locales))
	for _, loc := range locales {
		paths = append(paths, strconv.Quote("res://generated/translations/"+loc+".po"))
	}
	settings := []string{"locale/translations=PackedStringArray(" + strings.Join(paths, ", ") + ")", "locale/fallback=" + strconv.Quote(c.FallbackLocale), "locale/test=" + strconv.Quote(c.DefaultLocale)}
	lines := strings.Split(strings.TrimRight(raw, "\n"), "\n")
	out := []string{}
	inSection, found := false, false
	for _, line := range lines {
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			inSection = line == "[internationalization]"
			out = append(out, line)
			if inSection {
				found = true
				out = append(out, settings...)
			}
			continue
		}
		if inSection && (strings.HasPrefix(line, "locale/translations=") || strings.HasPrefix(line, "locale/fallback=") || strings.HasPrefix(line, "locale/test=")) {
			continue
		}
		out = append(out, line)
	}
	if !found {
		out = append(out, "", "[internationalization]")
		out = append(out, settings...)
	}
	return strings.Join(out, "\n") + "\n"
}

func writeGodotTranslations(project string, targets []string, c LocalizationCatalog) error {
	if len(targets) == 0 {
		return nil
	}
	files, err := godotPO(c)
	if err != nil {
		return err
	}
	seen := map[string]bool{}
	for _, target := range targets {
		if target == "" || filepath.IsAbs(target) {
			return fmt.Errorf("godot_targets must be project-relative directories")
		}
		dir := filepath.Clean(filepath.Join(project, target))
		if seen[dir] {
			return fmt.Errorf("duplicate Godot target %s", target)
		}
		seen[dir] = true
		path := filepath.Join(dir, "project.godot")
		raw, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("Godot target: %w", err)
		}
		dest := filepath.Join(dir, "generated", "translations")
		if err := os.MkdirAll(dest, 0o755); err != nil {
			return err
		}
		for locale, content := range files {
			if err := writeGeneratedFile(filepath.Join(dest, locale+".po"), content, 0o644); err != nil {
				return err
			}
		}
		if err := writeGeneratedFile(path, []byte(godotProjectLocales(string(raw), c)), 0o644); err != nil {
			return err
		}
	}
	return nil
}
