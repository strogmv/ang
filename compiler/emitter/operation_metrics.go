package emitter

import (
	"fmt"
	"path/filepath"
)

// Files of target.operation_metrics.
const (
	operationMetricsFile = "operation_metrics.gen.go" // internal/service
	dbObserveDir         = "dbobserve"                // internal/pkg/dbobserve
)

// emitOperationMetrics writes the helpers of target.operation_metrics: the
// per-operation timer every service method starts (internal/service) and
// the query tracer the Postgres pool gets (internal/pkg/dbobserve).
func (e *Emitter) emitOperationMetrics() error {
	if !e.OperationMetrics {
		return nil
	}
	files := map[string]string{
		filepath.Join("internal", "service", operationMetricsFile):     operationMetricsSource(e.GoModule),
		filepath.Join("internal", "pkg", dbObserveDir, "dbobserve.go"): dbObserveSource,
	}
	for rel, src := range files {
		formatted, err := formatGoStrict([]byte(src), rel)
		if err != nil {
			return err
		}
		if err := WriteFileIfChanged(e.outDir(rel), formatted, 0o644); err != nil {
			return fmt.Errorf("write %s: %w", rel, err)
		}
		logGenerated("Generated Operation Metrics: %s\n", rel)
	}
	return nil
}

func operationMetricsSource(goModule string) string {
	return `// Code generated by ANG. DO NOT EDIT.

package service

import (
	"context"
	stderrors "errors"
	"strconv"
	"time"

	"github.com/prometheus/client_golang/prometheus"
	"github.com/prometheus/client_golang/prometheus/promauto"
	"go.opentelemetry.io/otel"
	"go.opentelemetry.io/otel/attribute"
	"go.opentelemetry.io/otel/codes"

	apperrors "` + goModule + `/internal/pkg/errors"
)

// target.operation_metrics: every operation (HTTP handler, event subscriber,
// schedule, another service) runs inside observeOperation.
var (
	operationDuration = promauto.NewHistogramVec(prometheus.HistogramOpts{
		Name:    "ang_operation_duration_seconds",
		Help:    "Duration of service operations, by service, operation and outcome (ok, error).",
		Buckets: []float64{0.001, 0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1, 2.5, 5, 10, 30},
	}, []string{"service", "operation", "outcome"})

	operationErrors = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "ang_operation_errors_total",
		Help: "Service operations that returned an error, by the HTTP status the error carries (500 when it carries none).",
	}, []string{"service", "operation", "status"})

	operationTracer = otel.Tracer("ang/operations")
)

// observeOperation starts the span of an operation, points *ctx at the
// span's context and returns the function that ends the span with the error
// errp points at. A method calls it as
// defer observeOperation(&ctx, service, operation)(&err), which declares no
// name next to the operation's code. Without an OTLP endpoint the tracer is
// OpenTelemetry's no-op one.
func observeOperation(ctx *context.Context, service, operation string) func(*error) {
	start := time.Now()
	spanCtx, span := operationTracer.Start(*ctx, service+"."+operation)
	*ctx = spanCtx
	return func(errp *error) {
		var err error
		if errp != nil {
			err = *errp
		}
		outcome := "ok"
		if err != nil {
			outcome = "error"
			status := operationErrorStatus(err)
			operationErrors.WithLabelValues(service, operation, strconv.Itoa(status)).Inc()
			span.SetAttributes(attribute.Int("http.response.status_code", status))
			span.RecordError(err)
			if status >= 500 {
				span.SetStatus(codes.Error, err.Error())
			}
		}
		operationDuration.WithLabelValues(service, operation, outcome).Observe(time.Since(start).Seconds())
		span.End()
	}
}

func operationErrorStatus(err error) int {
	var problem *apperrors.ProblemDetail
	if stderrors.As(err, &problem) && problem.Status > 0 {
		return problem.Status
	}
	return 500
}
`
}

// dbObserveSource is internal/pkg/dbobserve: a pgx query tracer that records
// every query under the repository method that ran it.
const dbObserveSource = `// Code generated by ANG. DO NOT EDIT.

// Package dbobserve records metrics and spans for every Postgres query, by
// the repository method that ran it (target.operation_metrics).
package dbobserve

import (
	"context"
	"runtime"
	"strings"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/prometheus/client_golang/prometheus"
	"github.com/prometheus/client_golang/prometheus/promauto"
	"go.opentelemetry.io/otel"
	"go.opentelemetry.io/otel/attribute"
	"go.opentelemetry.io/otel/codes"
	"go.opentelemetry.io/otel/trace"
)

var (
	queryDuration = promauto.NewHistogramVec(prometheus.HistogramOpts{
		Name:    "ang_db_query_duration_seconds",
		Help:    "Duration of Postgres queries, by repository, method and outcome (ok, error).",
		Buckets: []float64{0.0005, 0.001, 0.0025, 0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1, 2.5, 5},
	}, []string{"repository", "method", "outcome"})

	queryRows = promauto.NewHistogramVec(prometheus.HistogramOpts{
		Name:    "ang_db_query_rows",
		Help:    "Rows a Postgres query returned or changed, by repository and method.",
		Buckets: []float64{0, 1, 10, 100, 1000, 10000, 100000},
	}, []string{"repository", "method"})

	queryErrors = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "ang_db_query_errors_total",
		Help: "Postgres queries that failed, by repository and method.",
	}, []string{"repository", "method"})

	tracer = otel.Tracer("ang/db")
)

// QueryTracer is a pgx.QueryTracer: set it as the pool's
// ConnConfig.Tracer. Queries inside a transaction are recorded too.
type QueryTracer struct{}

type queryKey struct{}

type queryStart struct {
	repository, method string
	start              time.Time
	span               trace.Span
}

// TraceQueryStart names the query by its caller and starts its span.
func (QueryTracer) TraceQueryStart(ctx context.Context, _ *pgx.Conn, _ pgx.TraceQueryStartData) context.Context {
	repository, method := caller()
	ctx, span := tracer.Start(ctx, "db "+repository+"."+method, trace.WithSpanKind(trace.SpanKindClient),
		trace.WithAttributes(attribute.String("db.system", "postgresql")))
	return context.WithValue(ctx, queryKey{}, &queryStart{repository: repository, method: method, start: time.Now(), span: span})
}

// TraceQueryEnd records the duration, the rows and the error.
func (QueryTracer) TraceQueryEnd(ctx context.Context, _ *pgx.Conn, data pgx.TraceQueryEndData) {
	q, ok := ctx.Value(queryKey{}).(*queryStart)
	if !ok {
		return
	}
	outcome := "ok"
	if data.Err != nil {
		outcome = "error"
		queryErrors.WithLabelValues(q.repository, q.method).Inc()
		q.span.RecordError(data.Err)
		q.span.SetStatus(codes.Error, data.Err.Error())
	} else {
		rows := data.CommandTag.RowsAffected()
		queryRows.WithLabelValues(q.repository, q.method).Observe(float64(rows))
		q.span.SetAttributes(attribute.Int64("db.response.returned_rows", rows))
	}
	queryDuration.WithLabelValues(q.repository, q.method, outcome).Observe(time.Since(q.start).Seconds())
	q.span.End()
}

// caller finds the repository method on the stack: the first frame of a
// package under internal/adapter/repository, "pkg.(*TenderRepository).ListByCompany"
// -> ("TenderRepository", "ListByCompany"). Queries from elsewhere are
// ("other", "other").
func caller() (string, string) {
	var pcs [32]uintptr
	n := runtime.Callers(3, pcs[:])
	frames := runtime.CallersFrames(pcs[:n])
	for {
		frame, more := frames.Next()
		if i := strings.Index(frame.Function, "/internal/adapter/repository/"); i >= 0 {
			name := frame.Function[i:]
			if dot := strings.Index(name, "."); dot >= 0 {
				name = name[dot+1:]
			}
			name = strings.NewReplacer("(*", "", ")", "").Replace(name)
			if repo, method, ok := strings.Cut(name, "."); ok {
				if j := strings.Index(method, "."); j >= 0 {
					method = method[:j] // a closure inside the method: func1
				}
				return repo, method
			}
		}
		if !more {
			return "other", "other"
		}
	}
}
`
