func renderEffectHandlerMap(def *normalizer.EffectHandlersDef) string {
	if def == nil || len(def.Bindings) == 0 {
		return "map[string]EffectHandler{}"
	}
	keys := make([]string, 0, len(def.Bindings))
	for k := range def.Bindings {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("map[string]EffectHandler{")
	for i, kind := range keys {
		if i > 0 {
			b.WriteString(", ")
		}
		item := def.Bindings[kind]
		b.WriteString(strconv.Quote(kind))
		b.WriteString(": {")
		b.WriteString("Kind: " + strconv.Quote(item.Kind))
		b.WriteString(", Driver: " + strconv.Quote(item.Driver))
		b.WriteString(", Provider: " + strconv.Quote(item.Provider))
		b.WriteString(", Options: " + renderAny(item.Options))
		b.WriteString("}")
	}
	b.WriteString("}")
	return b.String()
}

func renderEffectMiddlewareMap(def *normalizer.EffectMiddlewareCatalogDef) string {
	if def == nil || len(def.Chains) == 0 {
		return "map[string][]effectmw.EffectMiddleware{}"
	}
	keys := make([]string, 0, len(def.Chains))
	for k := range def.Chains {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("map[string][]effectmw.EffectMiddleware{")
	for i, kind := range keys {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(strconv.Quote(kind))
		b.WriteString(": {")
		for j, item := range def.Chains[kind] {
			if j > 0 {
				b.WriteString(", ")
			}
			b.WriteString("{")
			b.WriteString("Type: " + strconv.Quote(item.Type))
			b.WriteString(", Attempts: " + strconv.Itoa(item.Attempts))
			b.WriteString(", Backoff: " + strconv.Quote(item.Backoff))
			b.WriteString(", On: " + renderIntSlice(item.On))
			b.WriteString(", TTL: " + strconv.Quote(item.TTL))
			b.WriteString(", Key: " + strconv.Quote(item.Key))
			b.WriteString(", Duration: " + strconv.Quote(item.Duration))
			b.WriteString(", Level: " + strconv.Quote(item.Level))
			b.WriteString(", Options: " + renderAny(item.Options))
			b.WriteString("}")
		}
		b.WriteString("}")
	}
	b.WriteString("}")
	return b.String()
}

func renderIntSlice(items []int) string {
	if len(items) == 0 {
		return "nil"
	}
	var b strings.Builder
	b.WriteString("[]int{")
	for i, item := range items {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(strconv.Itoa(item))
	}
	b.WriteString("}")
	return b.String()
}

func renderAny(v any) string {
	switch x := v.(type) {
	case nil:
		return "nil"
	case string:
		return strconv.Quote(x)
	case bool:
		if x {
			return "true"
		}
		return "false"
	case int:
		return strconv.Itoa(x)
	case int64:
		return strconv.FormatInt(x, 10)
	case float64:
		return strconv.FormatFloat(x, 'f', -1, 64)
	case []int:
		return renderIntSlice(x)
	case []string:
		var b strings.Builder
		b.WriteString("[]string{")
		for i, item := range x {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(strconv.Quote(item))
		}
		b.WriteString("}")
		return b.String()
	case []any:
		var b strings.Builder
		b.WriteString("[]any{")
		for i, item := range x {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(renderAny(item))
		}
		b.WriteString("}")
		return b.String()
	case map[string]any:
		if len(x) == 0 {
			return "map[string]any{}"
		}
		keys := make([]string, 0, len(x))
		for k := range x {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		var b strings.Builder
		b.WriteString("map[string]any{")
		for i, key := range keys {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(strconv.Quote(key))
			b.WriteString(": ")
			b.WriteString(renderAny(x[key]))
		}
		b.WriteString("}")
		return b.String()
	default:
		return strconv.Quote(fmt.Sprintf("%v", x))
	}
}
