// Package crafting emits the independently testable crafting engine (doc 93) and its CUE catalog.
package crafting

import (
	"embed"
	"encoding/json"
	"fmt"
	"go/format"
	"strings"

	runtime "github.com/strogmv/ang/compiler/crafting/runtime"
)

//go:embed runtime/*.go
var sources embed.FS

// Render emits a standalone package and the exact validated CUE-derived catalog.
// The live adapter (custody, time, orders, gRPC) is the gamepoc host template.
func Render(catalog []byte) (map[string][]byte, error) {
	var model runtime.Model
	if err := json.Unmarshal(catalog, &model); err != nil {
		return nil, fmt.Errorf("crafting catalog: %w", err)
	}
	if err := model.Validate(); err != nil {
		return nil, err
	}
	out, err := RenderEngine()
	if err != nil {
		return nil, err
	}
	out["catalog.json"] = append([]byte(nil), catalog...)
	loader := []byte(`// Code generated by ANG. DO NOT EDIT.
package crafting
import (_ "embed"; "encoding/json")
//go:embed catalog.json
var catalogJSON []byte
// Catalog returns an independent validated model decoded from the CUE catalog.
func Catalog()(Model,error){var m Model;if err:=json.Unmarshal(catalogJSON,&m);err!=nil{return m,err};return m,m.Validate()}
`)
	out["catalog_data.gen.go"], err = format.Source(loader)
	if err != nil {
		return nil, err
	}
	out["catalog_generated_test.go"], err = format.Source([]byte(`// Code generated by ANG. DO NOT EDIT.
package crafting
import "testing"
func TestGeneratedCatalog(t *testing.T){m,err:=Catalog();if err!=nil{t.Fatal(err)};if err:=m.ValidateState(m.NewState());err!=nil{t.Fatal(err)}}
`))
	if err != nil {
		return nil, err
	}
	return out, nil
}

// RenderEngine emits the engine sources alone (a world without a crafting catalog still compiles the host adapter).
func RenderEngine() (map[string][]byte, error) {
	entries, err := sources.ReadDir("runtime")
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{}
	for _, entry := range entries {
		data, err := sources.ReadFile("runtime/" + entry.Name())
		if err != nil {
			return nil, err
		}
		name := strings.TrimSuffix(entry.Name(), ".go") + ".gen.go"
		if strings.HasSuffix(entry.Name(), "_test.go") {
			name = strings.TrimSuffix(entry.Name(), "_test.go") + "_generated_test.go"
		}
		data, err = format.Source(append([]byte("// Code generated by ANG. DO NOT EDIT.\n"), data...))
		if err != nil {
			return nil, fmt.Errorf("crafting %s: %w", entry.Name(), err)
		}
		out[name] = data
	}
	return out, nil
}
