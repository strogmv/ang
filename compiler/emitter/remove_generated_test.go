package emitter

import (
	"os"
	"path/filepath"
	"testing"
)

func TestRemoveGeneratedOutputKeepsHandWrittenFiles(t *testing.T) {
	root := t.TempDir()
	write := func(rel, content string) {
		path := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("internal/dto/a.go", "// Code generated by ANG. DO NOT EDIT.\n\npackage dto\n")
	write("internal/dto/sub/b.go", "// ============================================================================\n// AUTO-GENERATED by ANG (Architectural Normalized Generator)\n\npackage sub\n")
	write("internal/adapter/repository/memory/generated.go", "// Code generated by ANG. DO NOT EDIT.\n\npackage memory\n")
	write("internal/adapter/repository/memory/custom.go", "package memory\n\n// written by hand\n")
	write("sqlc.yaml", "# Code generated by ANG. DO NOT EDIT.\nversion: \"2\"\n")

	em := New(root, "", "templates")
	if err := em.RemoveGeneratedOutput("internal/dto", "internal/adapter/repository/memory", "sqlc.yaml", "does/not/exist"); err != nil {
		t.Fatal(err)
	}
	for _, gone := range []string{"internal/dto", "internal/adapter/repository/memory/generated.go", "sqlc.yaml"} {
		if _, err := os.Stat(filepath.Join(root, gone)); !os.IsNotExist(err) {
			t.Errorf("%s must be removed", gone)
		}
	}
	if _, err := os.Stat(filepath.Join(root, "internal/adapter/repository/memory/custom.go")); err != nil {
		t.Errorf("hand-written file must stay: %v", err)
	}
}
