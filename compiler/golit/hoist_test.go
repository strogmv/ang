package golit

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// table is a closed literal big enough to be worth a name.
func table() string {
	var rows strings.Builder
	for i := 0; i < 40; i++ {
		fmt.Fprintf(&rows, "\t\t\t{Code: %q, Days: %d},\n", fmt.Sprintf("C%02d", i), i)
	}
	return "(func() []struct {\n\t\tCode string\n\t\tDays int\n\t} {\n\t\t// One row per country.\n\t\treturn []struct {\n\t\t\tCode string\n\t\t\tDays int\n\t\t}{\n" + rows.String() + "\t\t}\n\t})"
}

func genFile(name, body string) string {
	return "// Code generated by test. DO NOT EDIT.\n\npackage svc\n\nimport (\n\t\"fmt\"\n\t\"strings\"\n)\n\n" + body + "\nvar _ = fmt.Sprint\n"
}

func TestHoistDirDeclaresRepeatedLiteralsOnceAndStillBuilds(t *testing.T) {
	dir := t.TempDir()
	mod := "module example.com/m\n\ngo 1.22\n"
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(mod), 0o644); err != nil {
		t.Fatal(err)
	}
	pkg := filepath.Join(dir, "svc")
	if err := os.MkdirAll(pkg, 0o755); err != nil {
		t.Fatal(err)
	}
	// a: the table inside a literal that captures `code` (stays), b: the
	// table on its own and a closed helper using strings (both hoisted).
	a := genFile("a", `func A(code string) int {
//line a.gen.go:13
	n := (func(c string) int {
		for _, r := range `+table()+`() {
			if r.Code == c {
				return r.Days
			}
		}
		return -1
	})(code)
	_ = code
//line a.gen.go:24
	return n + len(`+helper()+`("x"))
}
`)
	b := genFile("b", `func B() int {
	return len(`+table()+`()) + len(`+helper()+`(strings.TrimSpace(" y ")))
}
`)
	write := func(name, src string) {
		if err := os.WriteFile(filepath.Join(pkg, name), []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("a.gen.go", a)
	write("b.gen.go", b)
	write("hand.go", "package svc\n\nfunc Hand() int { return 1 }\n")

	st, err := HoistDir(pkg)
	if err != nil {
		t.Fatal(err)
	}
	if st.Hoisted != 2 || st.Replaced != 4 {
		t.Fatalf("want the table and the helper hoisted from 4 places, got %+v", st)
	}
	lits, _ := os.ReadFile(filepath.Join(pkg, File))
	if strings.Count(string(lits), "One row per country") != 1 || !strings.Contains(string(lits), `"strings"`) {
		t.Fatalf("the table is declared once, with its imports:\n%s", lits)
	}
	gotA, _ := os.ReadFile(filepath.Join(pkg, "a.gen.go"))
	if strings.Contains(string(gotA), "One row per country") || !strings.Contains(string(gotA), "(func(c string) int {") {
		t.Fatalf("the capturing literal stays, its table becomes a name:\n%s", gotA)
	}
	if strings.Contains(string(gotA), "\t\"strings\"") {
		t.Fatalf("an import only the hoisted literal used is dropped:\n%s", gotA)
	}
	for i, l := range strings.Split(string(gotA), "\n") {
		if strings.HasPrefix(l, "//line a.gen.go:") && l != fmt.Sprintf("//line a.gen.go:%d", i+2) {
			t.Fatalf("line %d: a directive must name the next line, got %q", i+1, l)
		}
	}
	cmd := exec.Command("go", "vet", "./...")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("the rewritten package must build: %v\n%s\n%s", err, out, lits)
	}

	// Idempotent: a second pass over its own output changes nothing.
	before := snapshot(t, pkg)
	if _, err := HoistDir(pkg); err != nil {
		t.Fatal(err)
	}
	if after := snapshot(t, pkg); after != before {
		t.Fatalf("a second pass must not change the package")
	}
}

func TestHoistDirLeavesSingleAndCapturingLiterals(t *testing.T) {
	pkg := t.TempDir()
	capt := "(func() int {\n\t\treturn len(s) + " + strings.Repeat("1 + ", 400) + "1\n\t})"
	src := genFile("c", "var s = \"x\"\n\nfunc C() int { return "+capt+"() + "+capt+"() }\n\nfunc D() int { return len("+table()+"()) }\n")
	if err := os.WriteFile(filepath.Join(pkg, "c.gen.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	st, err := HoistDir(pkg)
	if err != nil {
		t.Fatal(err)
	}
	if st.Hoisted != 0 || st.Replaced != 0 {
		t.Fatalf("a literal reading a variable and a literal used once stay: %+v", st)
	}
	if _, err := os.Stat(filepath.Join(pkg, File)); !os.IsNotExist(err) {
		t.Fatalf("no literals file when nothing is hoisted")
	}
}

func helper() string {
	return "(func(v string) string {\n\t\t// Trims and upper-cases; long on purpose.\n\t\tv = strings.TrimSpace(v)\n" +
		strings.Repeat("\t\tv = strings.ToUpper(strings.TrimSpace(v))\n", 30) + "\t\treturn v\n\t})"
}

func snapshot(t *testing.T, dir string) string {
	t.Helper()
	entries, _ := os.ReadDir(dir)
	var b strings.Builder
	for _, e := range entries {
		data, _ := os.ReadFile(filepath.Join(dir, e.Name()))
		b.WriteString(e.Name() + "\n" + string(data))
	}
	return b.String()
}

// A dry run hoists a scratch copy that holds only what the emitters wrote,
// reading the previous literals file from the project: it must produce the
// bytes a build produces hoisting the staged project in place. The previous
// file matters even where nothing is replaced: it makes every file tidied.
func TestHoistDirFromMatchesHoistingInPlace(t *testing.T) {
	fresh := map[string]string{
		"a.gen.go": genFile("a", "func A() int {\n\treturn len("+table()+"()) + len("+helper()+"(\"x\"))\n}\n"),
		"b.gen.go": genFile("b", "func B() int {\n\treturn len("+table()+"()) + len("+helper()+"(\" y \"))\n}\n"),
		// No literal; the trailing directive after the closing brace is how
		// the emitter leaves it and what tidying moves.
		"h.gen.go": "// Code generated by test. DO NOT EDIT.\n\npackage svc\n\nfunc H() int {\n//line ../../cue/h.cue:3\n\treturn 1\n}\n//line h.gen.go:9\n\nfunc G() int { return 2 }\n",
	}
	writeAll := func(dir string, files map[string]string) {
		t.Helper()
		for name, src := range files {
			if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o644); err != nil {
				t.Fatal(err)
			}
		}
	}
	// The project after its first build.
	project := t.TempDir()
	writeAll(project, fresh)
	if _, err := HoistDir(project); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(project, File)); err != nil {
		t.Fatalf("the first build declares the literals: %v", err)
	}
	projectBefore := snapshot(t, project)

	// The next build: the staged project with the emitters' output on top.
	staged := t.TempDir()
	entries, _ := os.ReadDir(project)
	for _, e := range entries {
		data, _ := os.ReadFile(filepath.Join(project, e.Name()))
		writeAll(staged, map[string]string{e.Name(): string(data)})
	}
	writeAll(staged, fresh)
	if _, err := HoistDir(staged); err != nil {
		t.Fatal(err)
	}

	// Its dry run: the emitters' output alone, the project's previous File.
	dry := t.TempDir()
	writeAll(dry, fresh)
	st, err := HoistDirFrom(dry, project)
	if err != nil {
		t.Fatal(err)
	}
	if got, want := snapshot(t, dry), snapshot(t, staged); got != want {
		t.Fatalf("dry run and build differ:\n--- build\n%s\n--- dry run\n%s", want, got)
	}
	if len(st.Retired) != 0 {
		t.Fatalf("nothing retired while the literals repeat: %v", st.Retired)
	}
	if snapshot(t, project) != projectBefore {
		t.Fatal("HoistDirFrom must not touch the previous directory")
	}

	// Nothing repeats any more: the previous File is retired.
	alone := t.TempDir()
	writeAll(alone, map[string]string{"a.gen.go": fresh["a.gen.go"]})
	st, err = HoistDirFrom(alone, project)
	if err != nil {
		t.Fatal(err)
	}
	if len(st.Retired) != 1 || st.Retired[0] != "." {
		t.Fatalf("Retired = %v, want [.]", st.Retired)
	}
	if _, err := os.Stat(filepath.Join(project, File)); err != nil {
		t.Fatalf("the project's File stays: %v", err)
	}
}
