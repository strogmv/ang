// Package schemavendor keeps a project's copy of ANG's CUE schema equal to the
// schema of the running ang binary, the revision the project's ang.lock pins.
//
// A project imports the schema as github.com/strogmv/ang/cue/schema. CUE
// resolves that path from cue.mod/pkg/github.com/strogmv/ang/cue/schema (the
// vendor directory, like Go's vendor/), which ANG owns: Sync writes every file
// of the binary's schema there and removes anything else, Plan lists what Sync
// would change. ang build syncs, ang build --check and ang validate fail on a
// difference, ang schema sync|check do just this (docs/schema.md).
package schemavendor

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	angschema "github.com/strogmv/ang/cue/schema"
)

// ImportPath is the CUE import path projects use for the schema.
const ImportPath = angschema.ImportPath

// ModulePath is ANG's own CUE module: projects inside it (examples/blog)
// import the schema from the repository and vendor nothing.
const ModulePath = "github.com/strogmv/ang"

// Header starts every vendored file.
const Header = "// Code generated by ang from " + ImportPath + ". DO NOT EDIT.\n" +
	"// ang build and ang schema sync keep it at the ANG revision ang.lock pins.\n\n"

// Change is one file Sync would write or remove, relative to the project.
type Change struct {
	Path   string `json:"path"`
	Action string `json:"action"` // create | update | delete
}

// Status is a project's vendored schema compared with the binary's.
type Status struct {
	// Applies is false when the project needs no vendored schema: no
	// cue.mod, ANG's own module, or (for a build) nothing imports it.
	Applies bool   `json:"applies"`
	Reason  string `json:"reason,omitempty"`
	// Dir is the vendor directory, relative to the project.
	Dir     string   `json:"dir,omitempty"`
	Changes []Change `json:"changes,omitempty"`
}

// InSync reports whether the vendored schema needs no change.
func (s Status) InSync() bool { return len(s.Changes) == 0 }

// Dir returns the vendor directory of a project.
func Dir(projectRoot string) string {
	return filepath.Join(projectRoot, "cue.mod", "pkg", filepath.FromSlash(ImportPath))
}

// Expected returns the vendored files by name: the binary's schema files, each
// with Header in front.
func Expected() (map[string][]byte, error) {
	files, err := angschema.Files()
	if err != nil {
		return nil, fmt.Errorf("read the embedded schema: %w", err)
	}
	out := make(map[string][]byte, len(files))
	for name, data := range files {
		out[name] = append([]byte(Header), data...)
	}
	return out, nil
}

// Options control when a project counts as using the schema.
type Options struct {
	// CueRoot is the project's CUE folder ("cue" when empty); its files are
	// searched for the import.
	CueRoot string
	// Always vendors even when no CUE file imports the schema yet (ang schema
	// sync, ang init). A build vendors only for a project that imports it or
	// already has the vendor directory.
	Always bool
}

// Plan compares the project's vendored schema with the binary's.
func Plan(projectRoot string, opts Options) (Status, error) {
	status, err := applies(projectRoot, opts)
	if err != nil || !status.Applies {
		return status, err
	}
	expected, err := Expected()
	if err != nil {
		return status, err
	}
	dir := Dir(projectRoot)
	existing, err := readDir(dir)
	if err != nil {
		return status, err
	}
	rel := func(name string) string { return filepath.ToSlash(filepath.Join(status.Dir, name)) }
	for _, name := range sortedKeys(expected) {
		current, ok := existing[name]
		switch {
		case !ok:
			status.Changes = append(status.Changes, Change{Path: rel(name), Action: "create"})
		case !bytes.Equal(current, expected[name]):
			status.Changes = append(status.Changes, Change{Path: rel(name), Action: "update"})
		}
	}
	for _, name := range sortedKeys(existing) {
		if _, ok := expected[name]; !ok {
			status.Changes = append(status.Changes, Change{Path: rel(name), Action: "delete"})
		}
	}
	return status, nil
}

// Sync makes the project's vendored schema equal to the binary's and returns
// what it changed.
func Sync(projectRoot string, opts Options) (Status, error) {
	status, err := Plan(projectRoot, opts)
	if err != nil || !status.Applies || status.InSync() {
		return status, err
	}
	expected, err := Expected()
	if err != nil {
		return status, err
	}
	dir := Dir(projectRoot)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return status, err
	}
	for _, change := range status.Changes {
		name := filepath.Base(filepath.FromSlash(change.Path))
		path := filepath.Join(dir, name)
		if change.Action == "delete" {
			if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
				return status, err
			}
			continue
		}
		if err := os.WriteFile(path, expected[name], 0o644); err != nil {
			return status, err
		}
	}
	return status, nil
}

var moduleRe = regexp.MustCompile(`(?m)^\s*module:\s*"([^"]+)"`)

// applies decides whether the project gets a vendored schema.
func applies(projectRoot string, opts Options) (Status, error) {
	status := Status{Dir: filepath.ToSlash(filepath.Join("cue.mod", "pkg", filepath.FromSlash(ImportPath)))}
	data, err := os.ReadFile(filepath.Join(projectRoot, "cue.mod", "module.cue"))
	if err != nil {
		if os.IsNotExist(err) {
			status.Reason = "no cue.mod/module.cue"
			return status, nil
		}
		return status, err
	}
	module := ""
	if m := moduleRe.FindSubmatch(data); m != nil {
		module, _, _ = strings.Cut(string(m[1]), "@")
	}
	if module == ModulePath || strings.HasPrefix(module, ModulePath+"/") {
		status.Reason = "the project is inside ANG's module and imports its schema directly"
		return status, nil
	}
	if opts.Always {
		status.Applies = true
		return status, nil
	}
	if info, err := os.Stat(Dir(projectRoot)); err == nil && info.IsDir() {
		status.Applies = true
		return status, nil
	}
	cueRoot := opts.CueRoot
	if cueRoot == "" {
		cueRoot = "cue"
	}
	imports, err := importsSchema(filepath.Join(projectRoot, cueRoot))
	if err != nil {
		return status, err
	}
	if !imports {
		status.Reason = "no CUE file imports " + ImportPath
		return status, nil
	}
	status.Applies = true
	return status, nil
}

// importsSchema reports whether a .cue file under root mentions the import
// path. A mention in a comment counts too: vendoring the schema then is
// harmless.
func importsSchema(root string) (bool, error) {
	needle := []byte(`"` + ImportPath + `"`)
	found := false
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			if os.IsNotExist(err) && path == root {
				return filepath.SkipDir
			}
			return err
		}
		if found {
			return filepath.SkipAll
		}
		if d.IsDir() || !strings.HasSuffix(d.Name(), ".cue") {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		found = bytes.Contains(data, needle)
		return nil
	})
	return found, err
}

func readDir(dir string) (map[string][]byte, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return map[string][]byte{}, nil
		}
		return nil, err
	}
	out := make(map[string][]byte, len(entries))
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		if err != nil {
			return nil, err
		}
		out[entry.Name()] = data
	}
	return out, nil
}

func sortedKeys(m map[string][]byte) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

// LegacyCopy reports a project folder that holds its own copy of ANG's schema
// (the layout before vendoring): <cueRoot>/schema with a file that declares
// #Operation and #FlowStep. Such a copy drifts from ANG; the project should
// import ImportPath instead and keep only its own definitions elsewhere.
func LegacyCopy(projectRoot, cueRoot string) (string, bool) {
	if cueRoot == "" {
		cueRoot = "cue"
	}
	dir := filepath.Join(projectRoot, cueRoot, "schema")
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", false
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".cue") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		if err != nil {
			continue
		}
		if legacyDeclRe.Match(data) && flowStepDeclRe.Match(data) {
			return filepath.ToSlash(filepath.Join(cueRoot, "schema")), true
		}
	}
	return "", false
}

var (
	legacyDeclRe   = regexp.MustCompile(`(?m)^#Operation:`)
	flowStepDeclRe = regexp.MustCompile(`(?m)^#FlowStep:`)
)
